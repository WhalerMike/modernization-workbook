def rows() -> list[dict]:
    """Each example as a dict keyed by the catalog's headers, with KSIs and window filled in."""
    out = []
    for values in _ROWS:
        row = dict(zip(_FIELDS, values))
        row.update(zip(["Identity type", "Identity sponsor", "High impact", "Human approval before action",
                        "Re-read by"], _SAFEGUARDS[row["Task ID"]]))
        row["KSIs"] = "; ".join(cs.ksis_for(cs.split_list(row["NIST SP 800-53 controls"])))
        row["Response window"] = cs.window_text(row["Severity"])
        out.append({name: row.get(name, "") for name in cs.HEADERS})
    return out
