def test_cli_dry_run_writes_files_and_makes_no_calls(tmp_path, monkeypatch):
    def boom(*a, **k):
        raise AssertionError("dry run must not call the network")

    monkeypatch.setattr(h, "http_post", boom)
    code = h.main(["--extract", str(FX / "hcm_extract_sample.csv"), "--out", str(tmp_path), "--as-of", "2026-10-25"])
    assert code == h.EXIT_QUARANTINE
    assert (tmp_path / "bulk-request-001.json").exists()
    assert (tmp_path / "validation-report.json").exists()
    assert (tmp_path / "quarantine.json").exists()
    assert not (tmp_path / "apply-results.json").exists()


def test_cli_apply_without_token_fails(tmp_path, monkeypatch):
    monkeypatch.delenv(h.TOKEN_ENV, raising=False)
    code = h.main(["--extract", str(FX / "hcm_extract_sample.csv"), "--out", str(tmp_path),
                   "--as-of", "2026-10-25", "--apply"])
    assert code == h.EXIT_ERROR


