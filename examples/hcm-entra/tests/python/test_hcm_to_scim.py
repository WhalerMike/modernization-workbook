# ---------------------------------------------------------------- apply, with a fake poster

ENDPOINT = "https://graph.microsoft.com/v1.0/servicePrincipals/00000000-0000-0000-0000-000000000000/synchronization/jobs/API2AAD.abc.def/bulkUpload"


def test_apply_posts_scim_json_and_records_the_logs_location(result, settings):
    calls, sleeps = [], []

    def poster(url, body, headers):
        calls.append((url, headers, json.loads(body)))
        return 202, {"Location": "https://graph.microsoft.com/v1.0/auditLogs/provisioning/?$filter=jobid eq 'x'"}, b""

    out = h.apply_batches(result.batches, ENDPOINT, "test-token", settings, poster=poster, sleeper=sleeps.append)
    assert len(calls) == 1
    url, headers, body = calls[0]
    assert url == ENDPOINT
    assert headers["Content-Type"] == "application/scim+json"
    assert headers["Authorization"] == "Bearer test-token"
    assert body == result.batches[0]
    assert out[0]["status"] == 202 and "auditLogs/provisioning" in out[0]["provisioning_logs"]
    assert sleeps == [settings["min_seconds_between_calls"]]


def test_apply_honors_retry_after_on_429(result, settings):
    responses = [(429, {"Retry-After": "7"}, b""), (202, {}, b"")]
    sleeps = []
    out = h.apply_batches(result.batches, ENDPOINT, "t", settings,
                          poster=lambda *a: responses.pop(0), sleeper=sleeps.append)
    assert sleeps[0] == 7.0
    assert out[0]["attempts"] == 2 and out[0]["status"] == 202


def test_apply_stops_on_first_failure(mapping, settings, rows):
    template = next(r for r in rows if r["PersonNumber"] == "100001")
    many = [dict(template, PersonNumber=f"3{i:05d}", ManagerPersonNumber="") for i in range(60)]
    res = h.convert(many, mapping, settings, AS_OF)
    out = h.apply_batches(res.batches, ENDPOINT, "t", settings,
                          poster=lambda *a: (403, {}, b""), sleeper=lambda s: None)
    assert len(out) == 1 and out[0]["status"] == 403


