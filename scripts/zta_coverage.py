#!/usr/bin/env python3
"""Generate the Zero Trust Assessment closure coverage page from its tracker.

data/zta-closure/coverage.yml lists every instruction ID of the Zero Trust
Assessment closure update (conventions G-01..G-08, book updates, the planned
Purview book's chapters, the guide items, the closure-map rows CM-01..CM-15 and ZTA-GUIDE),
with its wave, book, status, the pages that carry it and the pull request.
This script checks the file and writes the generated part of
docs/reference/zta-closure-coverage.md, between the coverage:start and
coverage:end comments. Everything outside the markers is hand-written.

    python scripts/zta_coverage.py           # rewrite the generated section
    python scripts/zta_coverage.py --check   # exit 1 if the file is invalid or the page is stale

The page tracks workbook guidance only, never a tenant's implementation.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "data" / "zta-closure" / "coverage.yml"
PAGE = REPO / "docs" / "reference" / "zta-closure-coverage.md"
START = "<!-- coverage:start: generated by scripts/zta_coverage.py from data/zta-closure/coverage.yml; edit those, not this section -->"
END = "<!-- coverage:end -->"
STATUSES = ("implemented", "partial", "planned", "deferred", "not-applicable")
KEYS = ("id", "title", "wave", "book", "status", "where", "pr", "note")
ID = re.compile(r"^(?:G-0[1-8]|B\d\d-\d\d|GSA-\d\d|XDR-\d\d|AZS-\d\d|CM-\d\d|ZTA-GUIDE)$")
GROUPS = (
    ("Global conventions", "Defined once in [Book 00, Appendix D](../books/b00-orientation/appendix-d-control-states-and-evidence.md).", r"^G-"),
    ("Updates to existing books", "", r"^B(?!20)\d\d-"),
    ("B20: Information Protection & Microsoft Purview (planned book)", "The planned twentieth book. The instructions number it nineteenth; it is numbered 20 because the workbook's Book 19 already exists.", r"^B20-"),
    ("Implementation guides", "Global Secure Access, Defender XDR and Azure security engineering are implementation guides, not books, by the workbook owner's decision of November 11, 2026, so they don't duplicate Books 09, 10 and 12. The Zero Trust Assessment tool guide is planned too.", r"^(?:GSA|XDR|AZS)-|^ZTA-GUIDE$"),
    ("Closure map", "Each finding family from the instructions' closure map, and the books and guides that carry it.", r"^CM-"),
)
LABEL = {"implemented": "Implemented", "partial": "Partial", "planned": "Planned", "deferred": "Deferred",
         "not-applicable": "Not applicable"}


def load(path: Path = DATA) -> list[dict]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))["items"]


def problems(items: list[dict], repo: Path = REPO) -> list[str]:
    out, seen = [], set()
    for n, it in enumerate(items, 1):
        name = it.get("id", f"item {n}")
        missing = [k for k in KEYS if k not in it]
        if missing:
            out.append(f"{name}: missing {', '.join(missing)}")
            continue
        if not ID.match(str(it["id"])):
            out.append(f"{name}: id doesn't match the instruction ID pattern")
        if it["id"] in seen:
            out.append(f"{name}: duplicate id")
        seen.add(it["id"])
        if it["status"] not in STATUSES:
            out.append(f"{name}: status must be one of {', '.join(STATUSES)}")
        if it["wave"] not in (None, 1, 2, 3, 4):
            out.append(f"{name}: wave must be 1 to 4 or null")
        if it["status"] in ("implemented", "partial") and not it["where"]:
            out.append(f"{name}: {it['status']} needs at least one path in where")
        if it["status"] in ("not-applicable", "deferred") and not it["note"]:
            out.append(f"{name}: {it['status']} needs a reason in note")
        for w in it["where"] or []:
            if not (repo / str(w).split("#", 1)[0]).exists():
                out.append(f"{name}: where path {w} doesn't exist")
    return out


def link(path: str) -> str:
    """A link from docs/reference/ to a repo path: published pages relative, anything else on GitHub."""
    file, _, anchor = path.partition("#")
    label = file.rsplit("/", 1)[-1] + (f"#{anchor}" if anchor else "")
    if file.startswith("docs/") and file.endswith(".md") and "/_" not in file:
        rel = Path(file).relative_to("docs")
        return f"[{label}](../{rel.as_posix()}{'#' + anchor if anchor else ''})"
    return f"[{label}](https://github.com/WhalerMike/modernization-workbook/blob/main/{file})"


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(items: list[dict]) -> str:
    counts = Counter(it["status"] for it in items)
    lines = [START, "", "## Summary {#summary}", "",
             f"{len(items)} instruction IDs: " + "; ".join(f"{LABEL[s]} {counts[s]}" for s in STATUSES) + ".", "",
             "| Group | IDs | Implemented | Partial | Planned | Deferred | Not applicable |",
             "|---|---|---|---|---|---|---|"]
    for title, _, pattern in GROUPS:
        group = [it for it in items if re.match(pattern, it["id"])]
        c = Counter(it["status"] for it in group)
        lines.append(f"| {title} | {len(group)} | " + " | ".join(str(c[s]) for s in STATUSES) + " |")
    lines += ["", ": Workbook guidance coverage by group {.striped}", ""]
    for title, intro, pattern in GROUPS:
        group = [it for it in items if re.match(pattern, it["id"])]
        lines += [f"## {title}", ""]
        if intro:
            lines += [intro, ""]
        lines += ["| ID | Item | Wave | Book | Status | Where | PR | Note |", "|---|---|---|---|---|---|---|---|"]
        for it in group:
            where = "; ".join(link(w) for w in it["where"] or []) or "—"
            pr = f"[#{it['pr']}](https://github.com/WhalerMike/modernization-workbook/pull/{it['pr']})" if it["pr"] else "—"
            wave = it["wave"] if it["wave"] is not None else "—"
            lines.append(f"| {it['id']} | {cell(it['title'])} | {wave} | {cell(it['book'])} | {LABEL[it['status']]} | "
                         f"{where} | {pr} | {cell(it['note']) or '—'} |")
        lines += ["", f": {title} {{.striped .hover}}", ""]
    lines.append(END)
    return "\n".join(lines)


def updated(page_text: str, body: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(page_text):
        raise SystemExit(f"{PAGE.relative_to(REPO)}: no coverage:start/coverage:end markers")
    return pattern.sub(lambda m: body, page_text, count=1)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the data is invalid or the page is stale")
    args = ap.parse_args(argv)
    items = load()
    bad = problems(items)
    for p in bad:
        print(f"{DATA.relative_to(REPO).as_posix()}: {p}")
    text = PAGE.read_text(encoding="utf-8")
    new = updated(text, render(items))
    if args.check:
        stale = new != text
        if stale:
            print(f"{PAGE.relative_to(REPO).as_posix()} is stale: run python scripts/zta_coverage.py")
        print(f"{len(items)} item(s); {len(bad)} problem(s)" + ("; page stale" if stale else ""))
        return 1 if bad or stale else 0
    if bad:
        return 1
    if new != text:
        PAGE.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {PAGE.relative_to(REPO).as_posix()}")
    print(f"{len(items)} item(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
