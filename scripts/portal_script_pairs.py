#!/usr/bin/env python3
"""Portal | PowerShell tabs: each Microsoft Learn portal image in the guides, beside the scripted step.

data/portal-script-pairs.yml pairs every Learn image in the guides (figure ids fig-learn-*) with the
script that does the same thing (`tab: exact`) or a related one (`tab: related`, with a sentence on how it
differs), or records why it has no tab (`tab: none`: a Learn diagram, or no script yet). For each tab this
script writes a tabset into the guide, in place of the figure:

  Portal                    the Learn image, unchanged
  PowerShell 7 / Windows    the command, what it printed (a terminal image, run on the kit's fixtures),
  PowerShell 5.1 / Bash     the lab it comes from, and the requirements and KSIs it produces evidence
                            for, copied from the kit's requirements map

The terminal output comes from an existing lab capture (`capture: wb/NN-k`, scripts/kit_captures.py) or,
for `run:` entries, from running the command on the kit's fixtures in the edition the kit declares
(Windows PowerShell 5.1 or PowerShell 7). `command:` entries need a live tenant or device: the command is
shown, with what it needs, and no output.

    python scripts/portal_script_pairs.py              # write the tabs into the guides
    python scripts/portal_script_pairs.py --capture    # run the `run:` commands, write their captures
    python scripts/portal_script_pairs.py --check      # exit 1 if the data, a capture or a page is wrong

--capture runs on Windows (Windows PowerShell 5.1 and PowerShell 7, Consolas for the images); the
"Script captures" workflow (.github/workflows/script-captures.yml) runs it on a fresh GitHub-hosted
runner and hands back the files.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import kit_captures as kc  # noqa: E402

DATA = ROOT / "data" / "portal-script-pairs.yml"
TEXT = ROOT / "data" / "kit-captures" / "guides"
PNGS = ROOT / "docs" / "books" / "guides" / "captures"
GH = kc.GH
BEGIN = "<!-- pair:begin {} (generated by scripts/portal_script_pairs.py from data/portal-script-pairs.yml) -->"
END = "<!-- pair:end -->"
BLOCK = re.compile(r"^<!-- pair:begin (\S+) [^\n]*-->\n.*?^<!-- pair:end -->\n", re.S | re.M)
FIG = re.compile(r"^!\[.*\{#(fig-learn-[\w-]+)[^\n]*\}[ \t]*$", re.M)
EDITION = {"5.1": ("Windows PowerShell 5.1", "powershell"), "7": ("PowerShell 7", "pwsh")}


def load() -> list[dict]:
    return yaml.safe_load(DATA.read_text(encoding="utf-8"))["pairs"]


def run_id(e: dict) -> str:
    return f"{Path(e['page']).stem}--{e['figure']}"


def capture_files(e: dict) -> tuple[Path, Path] | None:
    """(text, image) of the pair's terminal output, if it has one."""
    if "capture" in e:
        wb, key = e["capture"].split("/")
        return ROOT / "data" / "kit-captures" / wb / f"{key}.txt", ROOT / kc.WORKBOOKS[wb][0] / "captures" / f"{key}.png"
    if "run" in e:
        return TEXT / f"{run_id(e)}.txt", PNGS / f"{run_id(e)}.png"
    return None


def shown_commands(text: str) -> tuple[str, str]:
    """The commands a capture shows (without prompts), and its language."""
    lines, lang = [], "powershell"
    for l in text.split("\n"):
        for p in ("PS> ", ">> ", "$ ", "> "):
            if l.startswith(p):
                lines.append(l[len(p):])
                if p == "$ ":
                    lang = "bash"
                break
    return "\n".join(lines), lang


def rel(page: Path, target: Path) -> str:
    return Path(os.path.relpath(target, page.parent)).as_posix()


def requirement_row(req: dict) -> dict | None:
    """The row of the kit's requirements map that `req` names (JSON maps), or None if it can't be read.

    The kits shape their maps three ways: {"steps": {"ID": {...}}}, {"steps": [{"step": "id", ...}]} and
    {"rows": [{"id": "R-..", ...}]}. KSIs are under "ksi" or "ksis"."""
    path = ROOT / req["file"]
    if path.suffix != ".json":
        return None
    d = json.loads(path.read_text(encoding="utf-8"))
    steps = d.get("steps")
    if isinstance(steps, dict) and req["step"] in steps:
        return steps[req["step"]]
    for row in (steps if isinstance(steps, list) else []) + d.get("rows", []):
        if req["step"] in (row.get("step"), row.get("id")):
            return row
    return None


def ksis(row: dict) -> list[str]:
    return row.get("ksi") or row.get("ksis") or []


def evidence(page: Path, req: dict) -> str:
    parts = []
    if req.get("controls"):
        parts.append("NIST SP 800-53 Rev. 5 " + ", ".join(req["controls"]))
    if req.get("ksi"):
        parts.append("FedRAMP 20x KSIs " + ", ".join(req["ksi"]))
    if req.get("other"):
        parts.append("; ".join(req["other"]))
    return (f"**Evidence this step supports:** {'; '.join(parts)} (step `{req['step']}` in "
            f"[{Path(req['file']).name}]({GH}/{req['file']})).")


RUN_NOTE = (r" `$Run` is the lab's dated run folder under `C:\FMWLabs\results`, which its first steps set, so each run "
            "keeps its own results and the kit's folder stays as you unzipped it.")


def lab_link(page: Path, e: dict, code: str = "") -> str:
    if "capture" in e:
        wb, key = e["capture"].split("/")
        chapter = next((ROOT / kc.WORKBOOKS[wb][0]).glob(f"{key[:2]}-*.md"))
        fm = yaml.safe_load(chapter.read_text(encoding="utf-8").split("---", 2)[1]) or {}
        title = str(fm.get("title") or chapter.stem)
        return (f"From Lab 1 of [{title}]({rel(page, chapter)}), run on the kit's fixtures "
                f"([the same output as text]({GH}/data/kit-captures/{wb}/{key}.txt)); the lab's earlier steps come first."
                + (RUN_NOTE if "$Run" in code else ""))
    if "run" in e:
        return f"Run from `{e['run']['cwd']}` on the kit's own fixtures ([the same output as text]({GH}/data/kit-captures/guides/{run_id(e)}.txt))."
    return f"Needs {e['needs']}, so there's no captured output."


def tabset(page: Path, e: dict, figure: str) -> str:
    files = capture_files(e)
    if files:
        text = files[0].read_text(encoding="utf-8")
        code, lang = shown_commands(text)
        label = "Bash" if lang == "bash" else EDITION[e.get("run", {}).get("edition", "7")][0]
    else:
        code, lang = e["command"], "bash" if e["edition"] == "Bash" else "powershell"
        label = e["edition"]
    out = [BEGIN.format(e["figure"]), "", '::: {.panel-tabset group="portal-script"}', "", "#### Portal", "", figure, "",
           f"#### {label}", ""]
    if e["tab"] == "related":
        out += [f"*Related script.* {e['relation']}", ""]
    out += [f"```{lang}", code.rstrip(), "```", ""]
    if files:
        first = code.split("\n", 1)[0]
        cmd = (first if len(first) <= 80 else first[:77] + "…").replace('"', "'")
        out += [f"![What it prints, run on the kit's fixtures]({rel(page, files[1])})"
                "{.lightbox " f'fig-alt="Terminal window showing {cmd} and what it printed"}}', ""]
    out += [lab_link(page, e, code), ""]
    if e.get("requirements"):
        out += [evidence(page, e["requirements"]), ""]
    out += [":::", "", END]
    return "\n".join(out) + "\n"


def write_pages(pairs: list[dict], check: bool = False) -> list[str]:
    problems = []
    by_page: dict[str, list[dict]] = {}
    for e in pairs:
        by_page.setdefault(e["page"], []).append(e)
    for page_rel, entries in sorted(by_page.items()):
        page = ROOT / page_rel
        md = page.read_text(encoding="utf-8")
        # Undo earlier tabs: each block gives back its figure line.
        md = BLOCK.sub(lambda m: re.search(r"^(!\[.*\{#" + re.escape(m.group(1)) + r"[^\n]*\})$", m.group(0), re.M).group(1) + "\n", md)
        new = md
        for e in entries:
            files = capture_files(e)
            if e["tab"] == "none" or (files and not all(f.exists() for f in files)):
                continue                              # no tab yet: validate() reports a missing capture
            m = re.search(r"^(!\[[^\n]*\{#" + re.escape(e["figure"]) + r"[ }][^\n]*)$", new, re.M)
            if not m:
                problems.append(f"{page_rel}: no figure {e['figure']}")
                continue
            new = new[:m.start()] + tabset(page, e, m.group(1)).rstrip("\n") + new[m.end():]
        current = page.read_text(encoding="utf-8")
        if check:
            if current != new:
                problems.append(f"{page_rel}: the tabs are out of date (run python scripts/portal_script_pairs.py)")
        elif current != new:
            page.write_text(new, encoding="utf-8", newline="\n")
            print(f"wrote {page_rel}")
    return problems


def validate(pairs: list[dict]) -> list[str]:
    problems, seen = [], set()
    figures = {}
    for page in sorted((ROOT / "docs/books/guides").glob("*.md")):
        for m in re.finditer(r"\{#(fig-learn-[\w-]+)", page.read_text(encoding="utf-8")):
            figures[(page.relative_to(ROOT).as_posix(), m.group(1))] = True
    for e in pairs:
        key = (e["page"], e["figure"])
        if key in seen:
            problems.append(f"{key}: listed twice")
        seen.add(key)
        if key not in figures:
            problems.append(f"{key}: no such Learn figure on the page")
        tab = e.get("tab")
        if tab not in ("exact", "related", "none"):
            problems.append(f"{key}: tab must be exact, related or none")
            continue
        if tab == "none":
            if not e.get("reason"):
                problems.append(f"{key}: a pair with no tab needs a reason")
            continue
        if tab == "related" and not e.get("relation"):
            problems.append(f"{key}: a related pair needs a relation")
        sources = [k for k in ("capture", "run", "command") if k in e]
        if len(sources) != 1:
            problems.append(f"{key}: give exactly one of capture, run or command")
            continue
        files = capture_files(e)
        if files and not all(f.exists() for f in files):
            problems.append(f"{key}: capture missing ({', '.join(f.relative_to(ROOT).as_posix() for f in files if not f.exists())})"
                            + ("; run python scripts/portal_script_pairs.py --capture" if "run" in e else ""))
        if "run" in e and e["run"].get("edition") not in EDITION:
            problems.append(f"{key}: run.edition must be 5.1 or 7")
        if "command" in e and not (e.get("edition") and e.get("needs")):
            problems.append(f"{key}: a command that isn't captured needs edition and needs")
        req = e.get("requirements")
        if req:
            if not (ROOT / req["file"]).exists():
                problems.append(f"{key}: requirements file {req['file']} doesn't exist")
                continue
            row = requirement_row(req)
            if req["file"].endswith(".json"):
                if row is None:
                    problems.append(f"{key}: step {req['step']} isn't in {req['file']}")
                else:
                    if sorted(req.get("controls") or []) != sorted(row.get("controls") or []):
                        problems.append(f"{key}: controls differ from step {req['step']} in {req['file']}")
                    if sorted(req.get("ksi") or []) != sorted(ksis(row)):
                        problems.append(f"{key}: KSIs differ from step {req['step']} in {req['file']}")
            elif req["step"] not in (ROOT / req["file"]).read_text(encoding="utf-8"):
                problems.append(f"{key}: step {req['step']} isn't named in {req['file']}")
    for page, fig in figures:
        if (page, fig) not in seen:
            problems.append(f"{page}: {fig} has no entry in data/portal-script-pairs.yml")
    return problems


def capture(pairs: list[dict]) -> int:
    runs = [e for e in pairs if "run" in e and e["tab"] != "none"]
    TEXT.mkdir(parents=True, exist_ok=True)
    for e in runs:
        label, exe = EDITION[e["run"]["edition"]]
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            shutil.copytree(ROOT / "examples", root / "examples", ignore=shutil.ignore_patterns(
                "out", "__pycache__", ".pytest_cache", "node_modules", "target", ".gradle"))
            res = kc.run_pwsh([(1, e["run"]["code"])], root / e["run"]["cwd"], root, exe=exe)
        text = kc.render("powershell", res.get(1, []))
        (TEXT / f"{run_id(e)}.txt").write_text(text + "\n", encoding="utf-8", newline="\n")
        kc.draw(text, PNGS / f"{run_id(e)}.png", f"{e['run']['cwd']}  ·  {label}  ·  fixture data")
        print(f"captured {run_id(e)} ({label})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--capture", action="store_true", help="run the run: commands and write their captures")
    mode.add_argument("--check", action="store_true", help="exit 1 if the data, a capture or a page is wrong")
    a = ap.parse_args()
    pairs = load()
    if a.capture:
        return capture(pairs)
    problems = validate(pairs)
    if a.check:
        problems += write_pages(pairs, check=True)
        for p in problems:
            print(p)
        n = sum(1 for e in pairs if e["tab"] != "none")
        print(f"portal-script pairs: {len(pairs)} Learn images, {n} with tabs; {len(problems)} problem(s)")
        return 1 if problems else 0
    write_pages(pairs)                                # pairs whose capture is missing keep their plain figure
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
