#!/usr/bin/env python3
"""The Learn coverage map: every Microsoft Learn identity page, and where the workbook covers it.

Two Learn folders are mapped, page by page (the rules for what counts as a page
and how its URL is derived are in scripts/source_watch/learn_pages.py):

- Windows Server identity: MicrosoftDocs/windowsserverdocs, WindowsServerDocs/identity/
  -> data/learn-coverage/windows-server-identity.yml
- Microsoft Entra: MicrosoftDocs/entra-docs, docs/ (without docs/identity/saas-apps/)
  -> data/learn-coverage/entra.yml

Each data file has one entry per Learn page. The script writes: `path` (the
source file in the Learn repository), `url`, `title`, `area` (the page's top
folder; for Entra's identity/ folder, the folder under it), `ms_date`,
`ms_topic`, `description` and `cited_by` (every workbook file that links the
page). A person keeps three fields, which every run preserves:

- `coverage`: cited, covered-uncited, not-covered, out-of-scope or unreviewed.
  A new page starts as unreviewed. A page that any workbook file links becomes
  cited (unless marked out-of-scope); a cited page whose last citation is
  removed goes back to unreviewed, for a person to look at again.
- `note`: free text: why it's out of scope, what a gap would need.
- `workbook`: optional list of workbook files (repository paths, with an
  optional #anchor) that cover the topic without citing the page.

A page that disappears from Learn keeps its entry with `gone: <date>`, until a
person deletes it. The file also stores the repositories' redirects
(`redirects`: old URL -> page URL), so a citation of a page's old address
counts for the page.

The workbook files scanned for citations are the tracked (and untracked, not
ignored) text files under docs/, examples/ and data/, and each deck's build.js
and narration (presentations/*/build.js, narration*.json,
*Narration_Script.md). The reference page and the data files themselves are
left out. URLs are compared without locale, query, anchor or trailing slash,
and lower-cased; docs.microsoft.com counts as learn.microsoft.com.

The reference page docs/reference/learn-coverage.md is generated from the
data between its learn-coverage:begin and learn-coverage:end markers.

    python scripts/learn_coverage.py              # refresh from Learn (network), rescan, write data and page
    python scripts/learn_coverage.py --offline    # rescan the workbook only; write data and page (no network)
    python scripts/learn_coverage.py --check      # exit 1 if the data or the page is stale (no network)
    python scripts/learn_coverage.py --report     # counts by side, area and coverage

Learn content is read from a shallow, sparse clone of each repository (only
the tracked folder's .md and .yml files and the redirect files, no images)
in a cache directory outside the repository: --cache, or $LEARN_COVERAGE_CACHE,
or ~/.cache/fmw-learn-coverage. Later runs fetch the latest commit into the
same clones. That is two git fetches instead of thousands of API calls. Needs
git and PyYAML.
"""

