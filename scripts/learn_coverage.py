# ------------------------------------------------------------------ Learn side

def sparse_patterns(site: lp.Site) -> list[str]:
    pats = [f"/{site.folder}/**/*.md", f"/{site.folder}/**/*.yml", "/.openpublishing.redirection*.json"]
    return pats + [f"!/{x}/" for x in site.exclude]


def git(*args: str, cwd: Path | None = None) -> str:
    out = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {out.stderr.strip()}")
    return out.stdout.strip()


def sync_clone(site: lp.Site, cache: Path, log) -> Path:
    """A shallow sparse clone of the site's repository at its branch's latest commit."""
    repo = cache / site.key
    if not (repo / ".git").exists():
        cache.mkdir(parents=True, exist_ok=True)
        log(f"cloning {site.repo} into {repo}")
        git("clone", "--depth", "1", "--filter=blob:none", "--sparse", "--branch", site.branch,
            f"https://github.com/{site.repo}.git", str(repo))
    else:
        log(f"fetching {site.repo} in {repo}")
        git("fetch", "--depth", "1", "origin", site.branch, cwd=repo)
        git("reset", "--hard", "FETCH_HEAD", cwd=repo)
    git("sparse-checkout", "set", "--no-cone", *sparse_patterns(site), cwd=repo)
    return repo


def iso_date(value) -> str:
    if isinstance(value, (dt.date, dt.datetime)):
        return value.strftime("%Y-%m-%d")
    s = str(value or "").strip()
    m = re.fullmatch(r"(\d{1,2})/(\d{1,2})/(\d{4})", s)
    if m:
        return f"{m.group(3)}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"
    return s


def clean_text(value) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def read_meta(path: Path) -> dict:
    """title, description, ms_date, ms_topic from a Learn page (.md front matter or .yml)."""
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    meta: dict = {}
    if path.suffix.lower() == ".yml":
        try:
            data = yaml.safe_load(text) or {}
        except yaml.YAMLError:
            data = {}
        if isinstance(data, dict):
            md = data.get("metadata") if isinstance(data.get("metadata"), dict) else {}
            meta = {"title": data.get("title") or md.get("title"),
                    "description": md.get("description") or data.get("summary"),
                    "ms.date": md.get("ms.date"), "ms.topic": md.get("ms.topic")}
    else:
        m = FRONT_MATTER.match(text)
        if m:
            try:
                fm = yaml.safe_load(m.group(1)) or {}
            except yaml.YAMLError:
                fm = {}
                for line in m.group(1).splitlines():
                    k, sep, v = line.partition(":")
                    if sep:
                        fm[k.strip()] = v.strip().strip("\"'")
            meta = fm if isinstance(fm, dict) else {}
        if not meta.get("title"):
            h = H1.search(text[m.end():] if m else text)
            if h:
                meta["title"] = h.group(1)
    return {"title": clean_text(meta.get("title")), "description": clean_text(meta.get("description")),
            "ms_date": iso_date(meta.get("ms.date")), "ms_topic": clean_text(meta.get("ms.topic"))}


def learn_pages(site: lp.Site, repo: Path) -> dict[str, dict]:
    """{url: entry} for every page of the site in the clone."""
    pages = {}
    base = repo / site.folder
    for f in sorted(base.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(repo).as_posix()
        if not lp.is_page(site, rel):
            continue
        url = lp.page_url(site, rel)
        pages[url] = {"path": rel, "url": url, "area": site.area(rel), **read_meta(f)}
    return pages


def redirect_target(site: lp.Site, value: str) -> str | None:
    if value.startswith("/"):
        value = f"https://{lp.HOST}{value}"
    return lp.norm(value)


def learn_redirects(site: lp.Site, repo: Path, pages: dict) -> dict[str, str]:
    """{old URL: page URL} from the repository's redirect files, chains followed, ending on a page."""
    raw: dict[str, str] = {}
    for f in sorted(repo.glob(".openpublishing.redirection*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8-sig"))
        except ValueError:
            continue
        for r in data.get("redirections", []):
            src, dest = r.get("source_path") or r.get("source_path_from_root", "").lstrip("/"), r.get("redirect_url", "")
            if not src or not dest or not src.startswith(site.build_folder + "/"):
                continue
            new = redirect_target(site, dest)
            if new:
                raw.setdefault(lp.page_url(site, src), new)
    out = {}
    for old in raw:
        url, seen = old, set()
        while url in raw and url not in seen:
            seen.add(url)
            url = raw[url]
        if url in pages and url != old and old not in pages:
            out[old] = url
    return dict(sorted(out.items()))


# ------------------------------------------------------------------ workbook side

def workbook_files(root: Path = ROOT) -> list[str]:
    """Repository-relative paths of the workbook files scanned for citations."""
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
                             cwd=root, capture_output=True, check=True)
        paths = sorted({p for p in out.stdout.decode("utf-8").split("\0") if p})
    except (OSError, subprocess.CalledProcessError):
        paths = sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file() and ".git" not in p.parts)
    keep = []
    for p in paths:
        if p.startswith(SCAN_SKIP) or p == PAGE_REL:
            continue
        if (p.startswith(SCAN_ROOTS) and Path(p).suffix.lower() in TEXT_SUFFIXES) or PRESENTATION_FILE.match(p):
            keep.append(p)
    return keep


def learn_links(text: str) -> set[str]:
    out = set()
    for m in LEARN_URL.finditer(text):
        url = m.group(0).rstrip(".,;:*_!?'")
        u = lp.norm(url)
        if u:
            out.add(u)
    return out


def citations(root: Path = ROOT, files: list[str] | None = None) -> dict[str, set[str]]:
    """{normalized Learn URL: {workbook files linking it}}."""
    cited: dict[str, set[str]] = defaultdict(set)
    for rel in files if files is not None else workbook_files(root):
        try:
            text = (root / rel).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if "microsoft.com" not in text:
            continue
        for url in learn_links(text):
            cited[url].add(rel)
    return cited


# ------------------------------------------------------------------ the data

def merge(site: lp.Site, fresh: dict[str, dict] | None, old: dict, cited: dict[str, set[str]],
          today: str, redirects: dict[str, str] | None = None) -> dict:
    """The site's data: fresh pages (or the stored ones when offline), hand fields kept, citations recomputed."""
    old_pages = {p["url"]: p for p in old.get("pages", [])}
    redirects = dict(old.get("redirects") or {}) if redirects is None else redirects
    if fresh is None:  # offline: the stored list is the page list
        fresh = {u: {k: v for k, v in p.items() if k in ("path", "url", "title", "area", "ms_date", "ms_topic",
                                                         "description", "gone")} for u, p in old_pages.items()}
        today = ""
    entries = {}
    for url, page in fresh.items():
        prev = old_pages.get(url)
        if prev is None:  # a renamed page: carry the hand fields from its old address
            prev = next((p for u, p in old_pages.items() if redirects.get(u) == url and u not in fresh), None)
        e = dict(page)
        if today:
            e.pop("gone", None)
        e["coverage"] = (prev or {}).get("coverage", "unreviewed")
        e["note"] = (prev or {}).get("note", "") or ""
        if (prev or {}).get("workbook"):
            e["workbook"] = list(prev["workbook"])
        entries[url] = e
    if today:  # pages gone from Learn: kept, marked, until a person removes them
        for url, p in old_pages.items():
            if url not in entries:
                e = {k: v for k, v in p.items() if k in FIELDS}
                e.setdefault("gone", today)
                entries[url] = e
    by_target = defaultdict(list)
    for o, n in redirects.items():
        by_target[n].append(o)
    for url, e in entries.items():
        files = set(cited.get(url, ()))
        for o in by_target.get(url, ()):
            files |= cited.get(o, set())
        e["cited_by"] = sorted(files)
        if files and e["coverage"] in ("unreviewed", "not-covered", "covered-uncited"):
            e["coverage"] = "cited"
        elif not files and e["coverage"] == "cited":
            e["coverage"] = "unreviewed"
    pages = [{k: e[k] for k in FIELDS if k in e} for _, e in sorted(entries.items(), key=lambda x: x[1]["path"].lower())]
    header = {k: old[k] for k in ("site", "name", "repo", "folder", "excluded", "commit", "fetched") if k in old}
    return {**header, "pages": pages, "redirects": dict(sorted(redirects.items()))}


def dump(data: dict) -> str:
    head = ("# Learn coverage map data: generated by scripts/learn_coverage.py.\n"
            "# Hand-kept per page: coverage, note, workbook (see docs/reference/learn-coverage.md).\n"
            "# After editing, run: python scripts/learn_coverage.py --offline\n")
    return head + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=10000, default_flow_style=False)


def load(site: lp.Site) -> dict:
    f = DATA / f"{site.key}.yml"
    if not f.exists():
        return {}
    return yaml.safe_load(f.read_text(encoding="utf-8")) or {}


def validate(site: lp.Site, data: dict, root: Path = ROOT) -> list[str]:
    errors = []
    for p in data.get("pages", []):
        where = f"data/learn-coverage/{site.key}.yml: {p.get('path')}"
        if p.get("coverage") not in COVERAGE:
            errors.append(f"{where}: coverage {p.get('coverage')!r} is not one of {', '.join(COVERAGE)}")
        wb = p.get("workbook") or []
        if not isinstance(wb, list):
            errors.append(f"{where}: workbook must be a list of repository paths")
            continue
        for w in wb:
            if not (root / str(w).split("#")[0]).exists():
                errors.append(f"{where}: workbook file {w} doesn't exist")
    return errors


# ------------------------------------------------------------------ the page

def md(text: str) -> str:
    return re.sub(r"([\\`*_\[\]<>|])", r"\\\1", text)


def published(path: str) -> bool:
    """A workbook page the site renders (so a relative link to it works)."""
    if not path.endswith((".md", ".qmd")) or any(p.startswith("_") for p in path.split("/")[:-1] + [Path(path).name]):
        return False
    return path.startswith(("docs/books/", "docs/presentations/", "docs/inspiration/", "docs/about/",
                            "docs/reference/", "docs/training/", "docs/evaluations/", "docs/project-plans/")) or path in (
        "docs/start-here.md", "docs/downloads.md", "docs/research/index.md")


_titles: dict[str, str] = {}


def file_title(path: str, root: Path = ROOT) -> str:
    if path not in _titles:
        title = ""
        if path.endswith((".md", ".qmd")):
            try:
                text = (root / path).read_text(encoding="utf-8", errors="replace")
            except OSError:
                text = ""
            m = FRONT_MATTER.match(text)
            if m:
                t = re.search(r"^title:\s*(.+?)\s*$", m.group(1), re.M)
                title = t.group(1).strip().strip("\"'") if t else ""
        _titles[path] = title
    return _titles[path]


def home_link(ref: str, root: Path = ROOT) -> str:
    path, _, anchor = str(ref).partition("#")
    title = file_title(path, root)
    book = re.match(r"docs/books/b(\d\d)-", path)
    if title and book:
        title = f"Book {book.group(1)}, {title}"
    if published(path):
        target = posixpath.relpath(path, "docs/reference") + (f"#{anchor}" if anchor else "")
        return f"[{md(title or path)}]({target})"
    target = GITHUB + path + (f"#{anchor}" if anchor else "")
    return f"[{md(title) if title else '`' + path + '`'}]({target})"


def homes(page: dict, root: Path = ROOT, limit: int = 2) -> str:
    refs = list(page.get("workbook") or [])
    cited = sorted(page.get("cited_by") or [], key=lambda p: (not published(p), not p.startswith("docs/books/"), p))
    refs += [c for c in cited if c not in refs]
    if not refs:
        return "—"
    shown = [home_link(r, root) for r in refs[:limit]]
    more = len(refs) - limit
    return "; ".join(shown) + (f"; and {more} more" if more > 0 else "")


CLAIMS_OK = " <!-- claims-ok: Microsoft's page title, as Learn publishes it -->"


def title_cell(page: dict) -> str:
    """The Learn page's linked title. A title such as "... to meet NIST SP 800-63 requirements" is
    Microsoft's, not a workbook claim, so check_claims.py is told so on that row."""
    cell = f"[{md(page['title'] or page['path'])}]({page['url']})"
    import check_claims  # scripts/check_claims.py
    return cell + CLAIMS_OK if check_claims.hits(f"| {cell} |") else cell


def counts_row(label: str, pages: list[dict]) -> str:
    live = [p for p in pages if not p.get("gone")]
    c = Counter(p["coverage"] for p in live)
    return f"| {label} | {len(live):,} | " + " | ".join(f"{c.get(k, 0):,}" for k in COVERAGE) + " |"


COUNTS_HEAD = ("| {} | Pages | " + " | ".join(COVERAGE_LABEL[k] for k in COVERAGE) + " |\n|---|"
               + "---:|" * (len(COVERAGE) + 1))


def render_block(sites: list[tuple[lp.Site, dict]], root: Path = ROOT) -> str:
    out = [BEGIN, ""]
    out += ["## Counts", "", COUNTS_HEAD.format("Side")]
    every = []
    for site, data in sites:
        out.append(counts_row(site.name, data["pages"]))
        every += data["pages"]
    out.append(counts_row("**Both sides**", every))
    out.append("")
    for site, data in sites:
        anchor = site.key
        live = [p for p in data["pages"] if not p.get("gone")]
        by_area = defaultdict(list)
        for p in live:
            by_area[p["area"]].append(p)
        out += [f"## {site.name} {{#{anchor}}}", "",
                f"From [{site.repo}](https://github.com/{site.repo}), folder `{site.folder}/`"
                + (", without " + ", ".join(f"`{x}/`" for x in site.exclude) if site.exclude else "")
                + (f", at commit `{str(data.get('commit', ''))[:7]}` ({data.get('fetched')})" if data.get("commit") else "")
                + ".", "", COUNTS_HEAD.format("Area")]
        for area in sorted(by_area):
            out.append(counts_row(f"[{area}](#{anchor}-{area})", by_area[area]))
        out.append("")
        for area in sorted(by_area):
            out += [f"### {area} {{#{anchor}-{area}}}", "", "| Learn page | Workbook home | Coverage |", "|---|---|---|"]
            for p in sorted(by_area[area], key=lambda p: p["path"].lower()):
                cov = COVERAGE_LABEL[p["coverage"]] if p["coverage"] in COVERAGE_LABEL else p["coverage"]
                out.append(f"| {title_cell(p)} | {homes(p, root)} | {cov} |")
            out.append("")
        gone = [p for p in data["pages"] if p.get("gone")]
        if gone:
            out += [f"### Gone from Learn {{#{anchor}-gone}}", "",
                    "Pages the coverage data still lists after Learn removed them. Check what replaced each one, "
                    "move its citations, then delete its entry.", "", "| Learn page | Gone since | Workbook home |", "|---|---|---|"]
            for p in gone:
                out.append(f"| {title_cell(p)} | {p['gone']} | {homes(p, root)} |")
            out.append("")
    out += ["## Gaps {#gaps}", "",
            "Pages a reviewer marked **not covered** (the workbook should cover the topic and doesn't) or "
            "**covered, not cited** (a workbook page covers the topic but doesn't link the Learn page).", ""]
    for kind in ("not-covered", "covered-uncited"):
        rows = [(site, p) for site, data in sites for p in data["pages"] if p["coverage"] == kind and not p.get("gone")]
        out += [f"### {COVERAGE_LABEL[kind]} {{#gaps-{kind}}}", ""]
        if not rows:
            out += ["None marked yet.", ""]
            continue
        out += ["| Learn page | Side and area | Workbook home | Note |", "|---|---|---|---|"]
        for site, p in rows:
            out.append(f"| {title_cell(p)} | {site.name}, {p['area']} | {homes(p, root)} | {md(p.get('note') or '')} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def write_page(text: str, block: str) -> str:
    if not BLOCK.search(text):
        raise SystemExit(f"{PAGE_REL}: no learn-coverage:begin / learn-coverage:end markers")
    return BLOCK.sub(lambda _m: block, text, count=1)


# ------------------------------------------------------------------ main

def build(offline: bool, cache: Path, log, root: Path = ROOT) -> list[tuple[lp.Site, dict]]:
    cited = citations(root)
    today = dt.date.today().isoformat()
    out = []
    for site in lp.SITES:
        old = load(site)
        if offline:
            if not old:
                raise SystemExit(f"data/learn-coverage/{site.key}.yml doesn't exist yet: run without --offline first")
            data = merge(site, None, old, cited, "")
        else:
            repo = sync_clone(site, cache, log)
            fresh = learn_pages(site, repo)
            redirects = learn_redirects(site, repo, fresh)
            data = merge(site, fresh, old, cited, today, redirects)
            data = {"site": site.key, "name": site.name, "repo": site.repo, "folder": site.folder + "/",
                    "excluded": [x + "/" for x in site.exclude], "commit": git("rev-parse", "HEAD", cwd=repo),
                    "fetched": today, "pages": data["pages"], "redirects": data["redirects"]}
            log(f"{site.name}: {len(fresh):,} pages, {len(redirects):,} redirects")
        out.append((site, data))
    return out


def report(sites: list[tuple[lp.Site, dict]]) -> str:
    lines = []
    for site, data in sites:
        live = [p for p in data["pages"] if not p.get("gone")]
        gone = len(data["pages"]) - len(live)
        lines.append(f"{site.name}: {len(live):,} pages" + (f" ({gone} gone from Learn)" if gone else ""))
        width = max([len(a) for a in {p["area"] for p in live}] + [4])
        lines.append(f"  {'area'.ljust(width)}  {'pages':>5}  " + "  ".join(f"{k:>15}" for k in COVERAGE))
        by_area = defaultdict(list)
        for p in live:
            by_area[p["area"]].append(p)
        for area in sorted(by_area) + ["(all)"]:
            ps = live if area == "(all)" else by_area[area]
            c = Counter(p["coverage"] for p in ps)
            lines.append(f"  {area.ljust(width)}  {len(ps):>5}  " + "  ".join(f"{c.get(k, 0):>15}" for k in COVERAGE))
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Build the Learn coverage map's data and reference page.")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--offline", action="store_true", help="rescan the workbook only (no network); write data and page")
    mode.add_argument("--check", action="store_true", help="exit 1 if the data or the page is stale (no network)")
    mode.add_argument("--report", action="store_true", help="print counts by side, area and coverage (no network)")
    ap.add_argument("--cache", type=Path, default=Path(os.environ.get("LEARN_COVERAGE_CACHE")
                                                        or Path.home() / ".cache" / "fmw-learn-coverage"),
                    help="where the Learn repository clones are kept (outside the repository)")
    args = ap.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    log = lambda msg: print(msg, file=sys.stderr, flush=True)  # noqa: E731

    if args.report:
        print(report([(s, load(s)) for s in lp.SITES]))
        return 0
    sites = build(offline=args.offline or args.check, cache=args.cache, log=log)
    errors = [e for site, data in sites for e in validate(site, data)]
    page_text = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
    new_page = write_page(page_text, render_block(sites))
    if args.check:
        stale = [f"data/learn-coverage/{s.key}.yml" for s, d in sites
                 if (DATA / f"{s.key}.yml").read_text(encoding="utf-8") != dump(d)]
        if new_page != page_text:
            stale.append(PAGE_REL)
        for e in errors:
            print(f"error: {e}")
        for f in stale:
            print(f"stale: {f}: run python scripts/learn_coverage.py --offline and commit the result")
        if errors or stale:
            return 1
        print(f"learn coverage: data and page current ({sum(len(d['pages']) for _, d in sites):,} pages)")
        return 0
    DATA.mkdir(parents=True, exist_ok=True)
    for site, data in sites:
        (DATA / f"{site.key}.yml").write_text(dump(data), encoding="utf-8", newline="\n")
    PAGE.write_text(new_page, encoding="utf-8", newline="\n")
    for e in errors:
        print(f"error: {e}")
    print(report(sites))
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
