#!/usr/bin/env python3
"""Write each book's version and revision history, and the Archive page.

The workbook is published in editions: a git tag `edition-YYYY.MM` (a second
cut in the same month is `edition-YYYY.MM.N`) with a GitHub Release that
carries that edition's built files: the Word editions, the decks, the
narration audio, the videos. data/editions.yml is the record of every
edition: its date, a summary, and one line per change for each book that
changed in it (scripts/cut_edition.py drafts the lines from the merged pull
requests). The asset list of each edition's Release is in
data/edition-assets/<edition>.json, written by `cut_edition.py --refresh-assets`.

From those two, this script writes:

  - a "Version and revision history" section at the end of every book,
    guide and developer workbook (between the `revisions:start` and
    `revisions:end` comments; don't edit inside them), and
  - the editions and other releases on docs/about/archive.md (between the
    `archive:start` and `archive:end` comments).

A book's version is 1.0 in the first edition it appears in, and goes up by
0.1 in each later edition that changes it. An edition's entry for a book can
set `version: "2.0"` to start a new major version.

    python scripts/generate_revisions.py           # write the sections
    python scripts/generate_revisions.py --check   # exit 1 if a section is stale or the record is wrong

The check also fails on an edition id that isn't `edition-YYYY.MM[.N]`, on
dates out of order, on a book the record names that doesn't exist, and, when
the clone has the edition tags (CI fetches them), on an edition with no tag.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import posixpath
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RECORD = ROOT / "data" / "editions.yml"
ASSETS = ROOT / "data" / "edition-assets"
ARCHIVE = ROOT / "docs" / "about" / "archive.md"
REPO = "WhalerMike/modernization-workbook"
GH = f"https://github.com/{REPO}"
EDITION_ID = re.compile(r"edition-(\d{4})\.(0[1-9]|1[0-2])(?:\.([1-9]\d*))?")
# Most changes a book's table shows for one edition; the rest are one link away.
SHOWN = 8

REV_START = "<!-- revisions:start: generated by scripts/generate_revisions.py from data/editions.yml; edit those, not this section -->"
REV_END = "<!-- revisions:end -->"
ARC_START = "<!-- archive:start: generated by scripts/generate_revisions.py from data/editions.yml and data/edition-assets/ -->"
ARC_END = "<!-- archive:end -->"
BLOCK = re.compile(r"<!-- (revisions|archive):start.*?<!-- \1:end -->\n?", re.S)
FOOTNOTE_DEF = re.compile(r"\[\^[^\]]+\]:")


@dataclass
class Unit:
    """A book, guide or developer workbook: one page carries its history."""
    id: str
    kind: str                     # book, guide, workbook
    page: Path                    # the page the section goes on
    paths: list[str] = field(default_factory=list)   # what counts as a change to it (cut_edition.py)


def units() -> dict[str, Unit]:
    found: dict[str, Unit] = {}
    for index in sorted((ROOT / "docs" / "books").glob("b[0-9][0-9]-*/index.md")):
        name = index.parent.name
        paths = [f"docs/books/{name}", f"docs/images/diagrams/{name}"]
        paths += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "presentations").glob(f"{name}*") if p.is_dir())
        found[name] = Unit(name, "book", index, paths)
    for guide in sorted((ROOT / "docs" / "books" / "guides").glob("[a-z]*.md")):
        uid = f"guides/{guide.stem}"
        found[uid] = Unit(uid, "guide", guide, [guide.relative_to(ROOT).as_posix(), f"docs/images/diagrams/{guide.stem}"])
    for index in sorted((ROOT / "docs" / "project-plans" / "developer-workbooks").glob("*/index.md")):
        uid = f"developer-workbooks/{index.parent.name}"
        found[uid] = Unit(uid, "workbook", index, [index.parent.relative_to(ROOT).as_posix()])
    return found


# ------------------------------------------------------------------ the record

class RecordError(Exception):
    pass


def edition_label(eid: str) -> str:
    return eid[len("edition-"):]


def anchor(eid: str) -> str:
    return "edition-" + edition_label(eid).replace(".", "-")


def as_date(value, where: str) -> dt.date:
    if isinstance(value, dt.date):
        return value
    try:
        return dt.date.fromisoformat(str(value))
    except ValueError:
        raise RecordError(f"{where}: date {value!r} is not YYYY-MM-DD") from None


def load(found: dict[str, Unit]) -> tuple[list[dict], list[dict]]:
    data = yaml.safe_load(RECORD.read_text(encoding="utf-8")) or {}
    editions = data.get("editions") or []
    releases = data.get("releases") or []
    errors, seen, last = [], set(), None
    for i, ed in enumerate(editions):
        eid = str(ed.get("id", ""))
        where = f"data/editions.yml: edition {eid or i + 1}"
        if not EDITION_ID.fullmatch(eid):
            errors.append(f"{where}: id must be edition-YYYY.MM or edition-YYYY.MM.N")
        if eid in seen:
            errors.append(f"{where}: listed twice")
        seen.add(eid)
        try:
            ed["date"] = as_date(ed.get("date"), where)
            if last and ed["date"] < last:
                errors.append(f"{where}: dated before the edition above it (oldest first)")
            last = ed["date"]
        except RecordError as e:
            errors.append(str(e))
        if not ed.get("summary"):
            errors.append(f"{where}: needs a summary")
        for uid, entry in (ed.get("units") or {}).items():
            if uid not in found:
                errors.append(f"{where}: no book, guide or developer workbook {uid!r}")
            if not isinstance(entry, dict) or not entry.get("changes"):
                errors.append(f"{where}: {uid}: needs a `changes:` list")
            elif "version" in entry and not re.fullmatch(r"\d+\.\d+", str(entry["version"])):
                errors.append(f"{where}: {uid}: version must look like 2.0")
    for r in releases:
        where = f"data/editions.yml: release {r.get('tag', '?')}"
        for key in ("tag", "title", "date", "kind"):
            if not r.get(key):
                errors.append(f"{where}: needs `{key}`")
        try:
            r["date"] = as_date(r.get("date"), where)
        except RecordError as e:
            errors.append(str(e))
        if EDITION_ID.fullmatch(str(r.get("tag", ""))):
            errors.append(f"{where}: an edition goes under `editions:`, not `releases:`")
    if errors:
        raise RecordError("\n".join(errors))
    return editions, releases


def check_tags(editions: list[dict]) -> list[str]:
    """Editions with no tag, when this clone has tags at all (a shallow clone may not)."""
    try:
        out = subprocess.run(["git", "tag", "-l"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return []
    tags = set(out.split())
    if not tags:
        return []
    return [ed["id"] for ed in editions if ed["id"] not in tags]


def assets_of(eid: str) -> list[dict]:
    path = ASSETS / f"{eid}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else []


# --------------------------------------------------------------- the sections

def versions(editions: list[dict], uid: str) -> list[tuple[str, dict, dict]]:
    """(version, edition, the unit's entry) for each edition that changed the unit."""
    rows, major, minor = [], 0, -1
    for ed in editions:
        entry = (ed.get("units") or {}).get(uid)
        if not entry:
            continue
        if "version" in entry:
            major, minor = (int(x) for x in str(entry["version"]).split("."))
        elif major == 0:
            major, minor = 1, 0
        else:
            minor += 1
        rows.append((f"{major}.{minor}", ed, entry))
    return rows


def cell(text: str) -> str:
    text = re.sub(r"\(#(\d+)\)", lambda m: f"([#{m.group(1)}]({GH}/pull/{m.group(1)}))", str(text).strip())
    return text.replace("|", "\\|")


def long_date(d: dt.date) -> str:
    return f"{d:%B} {d.day}, {d.year}"


def kind_name(unit: Unit) -> str:
    return {"book": "book", "guide": "guide", "workbook": "workbook"}[unit.kind]


def revisions_section(unit: Unit, editions: list[dict]) -> str:
    rel = posixpath.relpath(ARCHIVE.relative_to(ROOT).as_posix(), unit.page.parent.relative_to(ROOT).as_posix())
    history = f"{GH}/commits/main/{unit.paths[0]}"
    lines = [REV_START, "", "## Version and revision history {#version-history}", ""]
    rows = versions(editions, unit.id)
    if not rows:
        lines += [
            f"This {kind_name(unit)} has not been published in an edition yet. Each edition is kept, with its "
            f"Word editions, decks and videos, on the [Archive]({rel}) page. Every change so far is in the "
            f"[commit history]({history}).",
        ]
    else:
        version, ed, _ = rows[-1]
        lines += [
            f"**Version {version}**, in [edition {edition_label(ed['id'])}]({rel}#{anchor(ed['id'])}) "
            f"({long_date(ed['date'])}). Every edition is kept on the [Archive]({rel}) page; every change "
            f"between editions is in the [commit history]({history}).",
            "",
            "| Version | Edition | Date | Changes |",
            "|---|---|---|---|",
        ]
        for version, ed, entry in reversed(rows):
            changes = [cell(c) for c in entry["changes"]]
            if len(changes) > SHOWN:
                prior = [e["id"] for e in editions if e["date"] <= ed["date"] and e["id"] != ed["id"]]
                more = f"{GH}/compare/{prior[-1]}...{ed['id']}" if prior else f"{GH}/commits/{ed['id']}/{unit.paths[0]}"
                changes = changes[:SHOWN] + [f"and {len(changes) - SHOWN} more ([all changes]({more}))"]
            lines.append(f"| {version} | [{edition_label(ed['id'])}]({rel}#{anchor(ed['id'])}) | "
                         f"{ed['date'].isoformat()} | {'; '.join(changes)} |")
        lines += ["", ": Versions of this " + kind_name(unit) + ", newest first {.striped .hover}"]
    lines += ["", REV_END, ""]
    return "\n".join(lines)


ASSET_GROUPS = [
    (".docx", "Word editions"),
    (".pdf", "PDF editions"),
    (".pptx", "Decks"),
    (".zip", "Narration audio and kits"),
    (".mp4", "Videos"),
    (".vtt", "Caption tracks"),
]


def size(n: int) -> str:
    for unit, scale in (("GB", 1 << 30), ("MB", 1 << 20), ("KB", 1 << 10)):
        if n >= scale:
            return f"{n / scale:.1f} {unit}"
    return f"{n} bytes"


def archive_section(editions: list[dict], releases: list[dict], found: dict[str, Unit]) -> str:
    lines = [ARC_START, "", "## Editions", ""]
    if not editions:
        lines += ["No edition has been cut yet. The first, edition 2026.10, is being prepared.", ""]
    else:
        lines += ["| Edition | Date | Summary | Files |", "|---|---|---|---|"]
        for ed in reversed(editions):
            assets = assets_of(ed["id"])
            files = f"[{len(assets)} files]({GH}/releases/tag/{ed['id']})" if assets else f"[Release]({GH}/releases/tag/{ed['id']})"
            lines.append(f"| [{edition_label(ed['id'])}](#{anchor(ed['id'])}) | {ed['date'].isoformat()} | "
                         f"{cell(ed['summary'])} | {files} |")
        lines += ["", ": Every edition, newest first {.striped .hover}", ""]
        for ed in reversed(editions):
            label = edition_label(ed["id"])
            tag = f"{GH}/releases/tag/{ed['id']}"
            lines += [f"### Edition {label} {{#{anchor(ed['id'])}}}", "",
                      f"{long_date(ed['date'])}. {cell(ed['summary'])}", "",
                      f"- **Release:** [{ed['id']}]({tag}) · [source at this edition]({GH}/tree/{ed['id']})"]
            changed = [found[u] for u in (ed.get("units") or {}) if u in found]
            if changed:
                links = []
                for u in changed:
                    rel = posixpath.relpath(u.page.relative_to(ROOT).as_posix(), "docs/about")
                    links.append(f"[{u.id.split('/')[-1]}]({rel}#version-history)")
                lines.append(f"- **Changed in this edition ({len(changed)}):** " + ", ".join(links))
            assets = assets_of(ed["id"])
            total = sum(a["size"] for a in assets)
            if assets:
                lines.append(f"- **Files:** {len(assets)}, {size(total)} in all")
                lines.append("")
                for suffix, heading in ASSET_GROUPS + [("", "Other files")]:
                    group = [a for a in assets if a["name"].lower().endswith(suffix)] if suffix else [
                        a for a in assets if not a["name"].lower().endswith(tuple(s for s, _ in ASSET_GROUPS))]
                    if not group:
                        continue
                    base = f"{GH}/releases/download/{ed['id']}"
                    items = [f"[{a['name']}]({base}/{a['name']}) ({size(a['size'])})" for a in sorted(group, key=lambda a: a["name"].lower())]
                    title = f"{heading} ({len(group)}, {size(sum(a['size'] for a in group))})"
                    lines += [f'::: {{.callout-note collapse="true" title="{title}"}}', "",
                              *[f"- {item}" for item in items], "", ":::", ""]
            lines.append("")
    lines += ["## Other releases", "",
              "Kits and video sets released on their own, outside an edition.", ""]
    if releases:
        lines += ["| Release | Date | What it is |", "|---|---|---|"]
        for r in sorted(releases, key=lambda r: (r["date"], r["tag"]), reverse=True):
            lines.append(f"| [{cell(r['title'])}]({GH}/releases/tag/{r['tag']}) | {r['date'].isoformat()} | {cell(r['kind'])} |")
        lines += ["", ": Other releases, newest first {.striped .hover}", ""]
    lines += [ARC_END, ""]
    return "\n".join(lines)


def place(text: str, section: str) -> str:
    """Replace the generated block, or add it before the page's trailing footnote definitions."""
    if BLOCK.search(text):
        return BLOCK.sub(lambda _: section, text, count=1)
    lines = text.rstrip("\n").split("\n")
    cut = len(lines)
    i = len(lines) - 1
    while i >= 0:
        line = lines[i]
        if not line.strip() or FOOTNOTE_DEF.match(line) or line.startswith(("    ", "\t")):
            if FOOTNOTE_DEF.match(line):
                cut = i
            i -= 1
            continue
        break
    head = "\n".join(lines[:cut]).rstrip("\n")
    tail = "\n".join(lines[cut:])
    return head + "\n\n" + section + ("\n" + tail + "\n" if tail else "")


def outputs() -> dict[Path, str]:
    found = units()
    editions, releases = load(found)
    out = {}
    for unit in found.values():
        text = unit.page.read_bytes().decode("utf-8")
        out[unit.page] = place(text, revisions_section(unit, editions))
    text = ARCHIVE.read_bytes().decode("utf-8")
    out[ARCHIVE] = place(text, archive_section(editions, releases, found))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a section is stale or the record is wrong")
    args = ap.parse_args(argv)
    try:
        files = outputs()
        found = units()
        editions, _ = load(found)
    except RecordError as e:
        print(f"revisions: {e}", file=sys.stderr)
        return 1
    stale = [p for p, text in files.items() if p.read_bytes() != text.encode("utf-8")]
    untagged = check_tags(editions)
    if args.check:
        bad = False
        if stale:
            print("revisions: stale (run python scripts/generate_revisions.py): "
                  + ", ".join(p.relative_to(ROOT).as_posix() for p in stale), file=sys.stderr)
            bad = True
        if untagged:
            print("revisions: no tag for " + ", ".join(untagged), file=sys.stderr)
            bad = True
        return 1 if bad else 0
    for p in stale:
        p.write_bytes(files[p].encode("utf-8"))
    if untagged:
        print("revisions: warning: no tag for " + ", ".join(untagged), file=sys.stderr)
    print(f"revisions: {len(files) - 1} pages and the Archive page, {len(stale)} written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
