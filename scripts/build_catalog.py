#!/usr/bin/env python3
"""Build docs/new-look/catalog.json, the catalog behind the New Look Browse page.

The New Look preview (docs/new-look/) lists the workbook the way a training
catalog does: one card per learning path, implementation guide, developer
workbook, book, lab set and video series, with filters for type, role, topic,
level and status. This script builds that list from the pages themselves, so a
new learning path or workbook appears without anyone editing a list:

- Learning paths: every folder under docs/training/ with an index.md, plus the
  external paths (`research-type: external learning path`) and the paths in
  data/catalog-overrides.yml `extra-paths`. Modules are the folder's NN-*.md.
  Level, roles and total time come from the path's own "Level", "Who this path
  is for" (or "Roles") and "Total time" (or "Time") lines.
- Implementation and companion guides: docs/books/guides/*.md. Gates or steps are
  the guide's numbered "## Gate N" or "## Step N" headings.
- Developer workbooks: every folder under docs/project-plans/developer-workbooks/.
- Books: every docs/books/bNN-*/index.md; chapters are NN-*.md and appendices.
- Labs: one set per section of docs/training/labs.md (generated by
  scripts/generate_labs.py), counting its links to Lab 1 and Lab 2 sections.
- Video series: one per group in docs/presentations/videos.json.

Video length is the sum of the videos built from an item's pages
(data/video-durations.json, else the manifest's minutes). Reading time is the
path's stated total time, or else the words in its pages at 230 a minute.

Status: `review-status: approved` reads Approved and `pending` reads Draft. A
book without one reads Approved once every chapter says `status: baseline`
(the books table's Baseline), and Draft otherwise.

Roles, topics and levels the pages don't state come from
data/catalog-overrides.yml: role-name rules, topic keyword rules, the roles each
topic implies, and per-item corrections. A level the page doesn't state is
derived from its `audience`: Technical only reads Advanced, Technical and
Customer reads Intermediate, Executive without Technical reads Beginner, and
anything else Unrated.

Runs as a Quarto pre-render script (`project: pre-render` in _quarto.yml) and
by hand:

    python scripts/build_catalog.py          # write docs/new-look/catalog.json
    python scripts/build_catalog.py --check  # exit 1 if the file is out of date

Needs PyYAML (python3-yaml), which the site build already installs.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(os.environ.get("QUARTO_PROJECT_DIR") or Path(__file__).resolve().parent.parent)
OUTPUT = Path("docs/new-look/catalog.json")
OVERRIDES = Path("data/catalog-overrides.yml")

TYPES = ["Learning path", "Implementation guide", "Developer workbook", "Book", "Companion guide", "Lab", "Video series"]
LEVELS = ["Beginner", "Intermediate", "Advanced", "Unrated"]
STATUSES = ["Approved", "Draft", "Not tracked"]
WORDS_PER_MINUTE = 230
VIDEO_GROUPS = {
    "start": ("The Start series", "the-start-series"),
    "book": ("Book presentations and briefings", "book-presentations-and-briefings"),
    "research": ("Research presentations", "research"),
    "developer": ("Developer workbook chapter tours", "developer-workbook-chapter-tours"),
    "training": ("Learning path module videos", "training-learning-path-modules"),
    "interview": ("HR-driven identity interview set", "hr-driven-identity-interview-set"),
}

FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
WORD = re.compile(r"[A-Za-z0-9][A-Za-z0-9'’.-]*")
COMMENT = re.compile(r"<!--.*?-->", re.S)
NUMBERED = "[0-9][0-9]-*.md"


# ------------------------------------------------------------------ reading pages

def read(path: Path) -> tuple[dict, str]:
    """Front matter and body of a Markdown page."""
    text = path.read_text(encoding="utf-8")
    m = FRONT.match(text)
    if not m:
        return {}, text
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        meta = {}
    return (meta if isinstance(meta, dict) else {}), text[m.end():]


def words(paths: list[Path]) -> int:
    total = 0
    for p in paths:
        _, body = read(p)
        total += len(WORD.findall(COMMENT.sub("", body)))
    return total


def one_line(meta: dict) -> str:
    """A one-line description: the subtitle, else the description's first sentence."""
    text = str(meta.get("subtitle") or "").strip()
    if not text:
        text = str(meta.get("description") or "").strip()
        text = re.sub(r"^(Research (draft|under review)|Research):\s*", "", text)
        m = re.match(r"(.+?[.!?])(\s|$)", text)
        if m:
            text = m.group(1)
    text = re.sub(r"\s+", " ", text)
    if len(text) > 240:
        text = text[:237].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return text


def clean_title(title: str) -> str:
    return re.sub(r"\s+", " ", str(title)).strip()


def stated(body: str, label: str) -> str:
    """The value of a page's "**Label:** value." line or "| **Label** | value |" row."""
    m = re.search(r"\*\*" + label + r":\*\*\s*([^*\n]+)", body)
    if m:
        return m.group(1).strip().rstrip(".").strip()
    m = re.search(r"^\|\s*\*\*" + label + r"\*\*\s*\|\s*([^|\n]+)\|", body, re.M)
    return m.group(1).strip() if m else ""


def stated_minutes(body: str) -> int | None:
    """Minutes from "Total time: about 7 hours 20 minutes" or a Time row."""
    text = stated(body, "Total time") or stated(body, "Time")
    if not text:
        return None
    m = re.search(r"(\d+)\s*hours?(?:\s*(\d+)\s*minutes?)?", text, re.I)
    if m:
        return int(m.group(1)) * 60 + int(m.group(2) or 0)
    m = re.search(r"(\d+)\s*minutes?", text, re.I)
    return int(m.group(1)) if m else None


def path_roles(body: str) -> list[str]:
    """Role names from a path's "Who this path is for" table, or its Roles row."""
    m = re.search(r"^## Who this path is for\s*\n(.*?)(?=^## |\Z)", body, re.M | re.S)
    names: list[str] = []
    if m:
        for line in m.group(1).splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if line.startswith("|") and cells and cells[0] and cells[0].lower() != "role" and not set(cells[0]) <= set("-: "):
                names.append(cells[0].strip("* "))
    if not names:
        row = stated(body, "Roles")
        names = [n.strip() for n in re.split(r",|\band\b", row) if n.strip()]
    return names


def status_of(meta: dict) -> str:
    review = str(meta.get("review-status") or "").lower()
    if review == "approved":
        return "Approved"
    if review:
        return "Draft"
    return ""


def book_status(folder: Path) -> str:
    chapters = sorted(folder.glob(NUMBERED)) + sorted(folder.glob("appendix-*.md"))
    states = [str(read(p)[0].get("status") or "").lower() for p in chapters]
    return "Approved" if states and all(s == "baseline" for s in states) else "Draft"


def level_from(meta: dict, body: str) -> tuple[str, str]:
    text = stated(body, "Level").lower()
    for level in LEVELS[:3]:
        if level.lower() in text:
            return level, "page"
    audience = {str(a).lower() for a in (meta.get("audience") or [])}
    if audience == {"technical"}:
        return "Advanced", "audience"
    if audience == {"technical", "customer"}:
        return "Intermediate", "audience"
    if audience and "executive" in audience and "technical" not in audience:
        return "Beginner", "audience"
    return "Unrated", "none"


# ------------------------------------------------------------------ the catalog

class Builder:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.cfg = yaml.safe_load((root / OVERRIDES).read_text(encoding="utf-8")) or {}
        self.role_names = [r["name"] for r in self.cfg.get("roles", [])]
        self.role_rules = [(name, re.compile(p, re.I)) for name, p in self.cfg.get("role-rules", [])]
        self.topic_rules = [(name, re.compile(p, re.I)) for name, p in self.cfg.get("topics", [])]
        self.topic_roles = self.cfg.get("topic-roles", {}) or {}
        self.families = self.cfg.get("families", {}) or {}
        self.item_fix = self.cfg.get("items", {}) or {}
        self.videos = self._videos()
        self.path_roles: dict[str, list[str]] = {}

    # --- helpers

    def rel(self, p: Path) -> str:
        return p.relative_to(self.root).as_posix()

    def _videos(self) -> list[dict]:
        manifest = self.root / "docs/presentations/videos.json"
        if not manifest.exists():
            return []
        videos = json.loads(manifest.read_text(encoding="utf-8"))
        durations_file = self.root / "data/video-durations.json"
        durations = json.loads(durations_file.read_text(encoding="utf-8")) if durations_file.exists() else {}
        for v in videos:
            seconds = durations.get(v["id"])
            v["_seconds"] = float(seconds) if seconds else float(v.get("minutes") or 0) * 60
            v["_source"] = v.get("source") or str(v.get("page") or "").replace(".html", ".md")
        return videos

    def video_minutes(self, scope: str) -> tuple[int, int]:
        """(count, minutes) of the videos built from a page, or from any page under a folder."""
        hits = [v for v in self.videos if v["_source"] == scope or (scope.endswith("/") and v["_source"].startswith(scope))]
        return len(hits), round(sum(v["_seconds"] for v in hits) / 60)

    def map_roles(self, names: list[str]) -> list[str]:
        out: list[str] = []
        for n in names:
            for role, rx in self.role_rules:
                if rx.search(n):
                    if role not in out:
                        out.append(role)
                    break
        return out

    def topics_for(self, meta: dict, body: str) -> list[str]:
        head = " ".join([str(meta.get("title") or ""), str(meta.get("subtitle") or ""),
                         stated(body, "Products?"), stated(body, "Product")])
        found = [name for name, rx in self.topic_rules if rx.search(head)]
        if not found:
            desc = str(meta.get("description") or "")
            found = [name for name, rx in self.topic_rules if rx.search(desc)]
        return found

    def item(self, *, kind: str, source: str, url: str, meta: dict, body: str, count: int | None, unit: str,
             files: list[Path], scope: str, status: str, roles: list[str] | None = None,
             level: tuple[str, str] | None = None, title: str | None = None, description: str | None = None,
             family: str | None = None) -> dict:
        topics = self.topics_for(meta, body)
        lvl, lvl_source = level or level_from(meta, body)
        reading = stated_minutes(body) if kind == "Learning path" else None
        reading_source = "page" if reading else "estimate"
        if reading is None and files:
            reading = max(1, round(words(files) / WORDS_PER_MINUTE))
        vcount, vmin = self.video_minutes(scope) if scope else (0, 0)
        return {
            "id": source,
            "type": kind,
            "title": clean_title(title or meta.get("title") or Path(source).stem),
            "description": description or one_line(meta),
            "url": url.replace(".md", ".html").replace(".qmd", ".html"),
            "count": count,
            "unit": unit,
            "reading_minutes": reading,
            "reading_source": reading_source if reading else None,
            "videos": vcount,
            "video_minutes": vmin,
            "level": lvl,
            "level_source": lvl_source,
            "roles": roles or [],
            "topics": topics,
            "status": status or "Not tracked",
            "family": family or self.families.get(source),
            "featured": False,
        }

    # --- sources

    def learning_paths(self) -> list[dict]:
        items = []
        for index in sorted((self.root / "docs/training").glob("*/index.md")):
            folder = index.parent
            if folder.name.startswith("_"):
                continue
            meta, body = read(index)
            modules = sorted(folder.glob(NUMBERED))
            roles = self.map_roles(path_roles(body))
            self.path_roles[folder.name] = roles
            items.append(self.item(kind="Learning path", source=self.rel(index), url=self.rel(index), meta=meta,
                                   body=body, count=len(modules), unit="modules", files=[index, *modules],
                                   scope=self.rel(folder) + "/", status=status_of(meta), roles=roles,
                                   family=folder.name))
        for page in sorted((self.root / "docs/training").glob("*.md")):
            meta, body = read(page)
            if str(meta.get("research-type") or "").lower() != "external learning path":
                continue
            items.append(self.item(kind="Learning path", source=self.rel(page), url=self.rel(page), meta=meta,
                                   body=body, count=None, unit="modules", files=[page], scope=self.rel(page),
                                   status=status_of(meta), title=meta.get("title")))
        for extra in self.cfg.get("extra-paths", []) or []:
            modules = sorted(self.root.glob(extra["modules"]))
            if not modules:
                continue
            metas = [read(m)[0] for m in modules]
            states = [status_of(m) for m in metas]
            status = "Approved" if states and all(s == "Approved" for s in states) else "Draft"
            first_meta, first_body = read(self.root / extra["url"])
            meta = {"title": extra["title"], "description": extra.get("description", ""),
                    "subtitle": extra.get("description", "")}
            minutes = sum(self.video_minutes(self.rel(m))[1] for m in modules)
            vids = sum(self.video_minutes(self.rel(m))[0] for m in modules)
            it = self.item(kind="Learning path", source="path:" + extra["id"], url=extra["url"], meta=meta,
                           body="", count=len(modules), unit="modules", files=modules, scope="", status=status,
                           roles=list(extra.get("roles") or []),
                           level=(extra["level"], "override") if extra.get("level") else None,
                           family=extra["id"])
            it["videos"], it["video_minutes"] = vids, minutes
            items.append(it)
        return items

    def guides(self) -> list[dict]:
        items = []
        for page in sorted((self.root / "docs/books/guides").glob("*.md")):
            meta, body = read(page)
            name = page.stem
            research = str(meta.get("research-type") or "").lower()
            implementation = research == "implementation guide" or name.endswith(("-implementation", "-kit"))
            kind = "Implementation guide" if implementation else "Companion guide"
            numbered = re.findall(r"^## (Gate|Step) (\d+)\b", body, re.M)
            unit = "gates" if numbered and numbered[0][0] == "Gate" else "steps"
            gates = len({n for _, n in numbered})
            family = self.families.get(self.rel(page)) or re.sub(r"-implementation$", "", name)
            items.append(self.item(kind=kind, source=self.rel(page), url=self.rel(page), meta=meta, body=body,
                                   count=gates if gates >= 2 else None, unit=unit, files=[page],
                                   scope=self.rel(page), status=status_of(meta), family=family))
        return items

    def workbooks(self) -> list[dict]:
        items = []
        for index in sorted((self.root / "docs/project-plans/developer-workbooks").glob("*/index.md")):
            folder = index.parent
            meta, body = read(index)
            chapters = sorted(folder.glob(NUMBERED))
            items.append(self.item(kind="Developer workbook", source=self.rel(index), url=self.rel(index),
                                   meta=meta, body=body, count=len(chapters), unit="chapters",
                                   files=[index, *chapters], scope=self.rel(folder) + "/",
                                   status=status_of(meta), family=folder.name))
        return items

    def books(self) -> list[dict]:
        items = []
        for index in sorted((self.root / "docs/books").glob("b[0-9][0-9]-*/index.md")):
            folder = index.parent
            meta, body = read(index)
            chapters = sorted(folder.glob(NUMBERED))
            appendices = sorted(folder.glob("appendix-*.md"))
            status = status_of(meta) or book_status(folder)
            items.append(self.item(kind="Book", source=self.rel(index), url=self.rel(index), meta=meta, body=body,
                                   count=len(chapters) + len(appendices), unit="chapters",
                                   files=[index, *chapters, *appendices], scope=self.rel(folder) + "/",
                                   status=status, level=("Unrated", "none")))
        return items

    def labs(self, by_family: dict[str, dict]) -> list[dict]:
        page = self.root / "docs/training/labs.md"
        if not page.exists():
            return []
        meta, body = read(page)
        items = []
        sections = re.split(r"^## ", body, flags=re.M)[1:]
        for sec in sections:
            head, _, rest = sec.partition("\n")
            m = re.match(r"(.+?)\s*\{#([\w-]+)\}", head)
            if not m:
                continue
            name, anchor = m.group(1).strip(), m.group(2)
            rows = [line for line in rest.splitlines()
                    if line.startswith("| [") or (line.startswith("| ") and "Lab 1" in line and "](" in line)]
            if not rows:
                continue
            link = re.search(r"\]\(\.\./(project-plans/developer-workbooks|training)/([\w-]+)/index\.md\)", rest)
            if not link:
                link = re.search(r"\]\(()([\w-]+)/index\.md\)", rest)
            if not link:
                link = re.search(r"\]\(\.\./(books)/([\w-]+)/index\.md\)", rest)
            family = None
            if link:
                folder = link.group(1) or "training"
                family = self.families.get(f"docs/{folder}/{link.group(2)}/index.md") or link.group(2)
            if anchor == "ms-automation":
                family = "ms-automation"
            parent = by_family.get(family or "")
            title = "Labs: " + re.sub(r"^The\s+", "", name)
            fake_meta = {"title": title, "description": name}
            # Each lab is a link to a lab section (an anchor with "lab-1" or "lab-2" in it),
            # not counting the links to a lab's list of commands.
            labs = sum(len({t for t in re.findall(r"\]\(([^)\s]*#[^)\s]*lab-?[12][^)\s]*)\)", row)
                            if "commands" not in t}) for row in rows)
            it = self.item(kind="Lab", source=f"docs/training/labs.md#{anchor}", url=f"docs/training/labs.md#{anchor}",
                           meta=fake_meta, body="", count=labs, unit="labs", files=[], scope="",
                           status=(parent or {}).get("status") or status_of(meta),
                           level=((parent or {}).get("level", "Unrated"), "path"),
                           description=f"{labs} hands-on labs across {len(rows)} chapters or modules: Lab 1 runs on "
                                       f"the kit's fixtures with no tenant, Lab 2 in a test tenant. {name}.",
                           family=family)
            if parent:
                it["roles"] = list(parent["roles"])
                it["topics"] = list(parent["topics"])
            items.append(it)
        return items

    def video_series(self) -> list[dict]:
        items = []
        for group, (name, anchor) in VIDEO_GROUPS.items():
            vids = [v for v in self.videos if v.get("group") == group]
            if not vids:
                continue
            minutes = round(sum(v["_seconds"] for v in vids) / 60)
            items.append({
                "id": f"videos:{group}", "type": "Video series", "title": name,
                "description": f"{len(vids)} narrated videos with captions, playable in the browser or downloadable.",
                "url": f"docs/presentations/watch.html#{anchor}", "count": len(vids), "unit": "videos",
                "reading_minutes": None, "reading_source": None, "videos": len(vids), "video_minutes": minutes,
                "level": "Unrated", "level_source": "none", "roles": [], "topics": [],
                "status": "Not tracked", "family": None, "featured": False,
            })
        return items

    # --- assembly

    def build(self) -> dict:
        items = self.learning_paths()
        items += self.guides()
        items += self.workbooks()
        items += self.books()
        families = {it["family"]: it for it in items if it["type"] == "Learning path" and it.get("family")}
        items += self.labs(families)
        items += self.video_series()
        featured = set(self.cfg.get("featured") or [])
        for it in items:
            fix = self.item_fix.get(it["id"], {}) or {}
            if "type" in fix:
                it["type"] = fix["type"]
            if "level" in fix:
                it["level"], it["level_source"] = fix["level"], "override"
            if "topics" in fix:
                it["topics"] = list(fix["topics"])
            for t in fix.get("add-topics", []) or []:
                if t not in it["topics"]:
                    it["topics"].append(t)
            if "roles" in fix:
                it["roles"] = list(fix["roles"])
            elif not it["roles"]:
                roles: list[str] = []
                path = families.get(it.get("family") or "")
                if path:
                    roles += path["roles"]
                if it["type"] == "Developer workbook":
                    roles.append("Developer")
                for t in it["topics"]:
                    roles += self.topic_roles.get(t, [])
                if it["type"] in ("Book", "Companion guide") and "executive" in {
                        str(a).lower() for a in (read(self.root / it["id"])[0].get("audience") or [])}:
                    roles.append("Executive")
                it["roles"] = roles
            for r in fix.get("add-roles", []) or []:
                it["roles"].append(r)
            # Keep the configured order and drop repeats.
            it["roles"] = [r for r in self.role_names if r in set(it["roles"])]
            topic_order = [name for name, _ in self.topic_rules]
            it["topics"] = [t for t in topic_order if t in set(it["topics"])]
            if fix.get("featured") or it["id"] in featured:
                it["featured"] = True
        if not featured:
            for it in items:
                if it["type"] == "Learning path" and it["status"] == "Approved" and it["count"]:
                    it["featured"] = True
        items.sort(key=lambda it: (TYPES.index(it["type"]), it["title"].lower()))
        return {
            "generated_by": "scripts/build_catalog.py",
            "facets": {
                "type": TYPES,
                "role": self.role_names,
                "topic": [name for name, _ in self.topic_rules],
                "level": LEVELS,
                "status": STATUSES,
            },
            "roles": self.cfg.get("roles", []),
            "items": items,
        }


def render(root: Path = ROOT) -> str:
    return json.dumps(Builder(root).build(), ensure_ascii=False, indent=1) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/new-look/catalog.json is out of date")
    args = ap.parse_args(argv)
    out = ROOT / OUTPUT
    text = render(ROOT)
    current = out.read_text(encoding="utf-8") if out.exists() else ""
    if args.check:
        if current != text:
            print(f"{OUTPUT.as_posix()} is out of date: run python scripts/build_catalog.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.as_posix()} is current")
        return 0
    if current != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {OUTPUT.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
