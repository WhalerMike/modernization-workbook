#!/usr/bin/env python3
"""Build the topic hubs from data/topics.yml.

A topic hub is one page that ties together everything the workbook has on a topic: the book
chapters, the project plan and decisions, the implementation guides, the developer workbook and its
code, the learning path and labs, the videos, the Word and code downloads, and the evidence.

Writes, from data/topics.yml:

- docs/topics/<id>.md: one hub per topic.
- docs/topics/index.md: the Topics page, one row per topic with what it has of each kind.
- assets/topic-members.json: page -> its topics. assets/fmw-topics.lua reads it to show
  "Topic: <hub>" under the title of every page that belongs to a topic.

The developer workbook, implementation guide, learning path, labs and code zip of a topic come from
its `workbook:` entry in scripts/generate_labs.py, so they are listed in one place. Videos come from
docs/presentations/videos.json: every video whose source page belongs to the topic.

    python scripts/build_topics.py            # write the files
    python scripts/build_topics.py --check    # list what is out of date; write nothing

The pages are committed (they're generated, like the Labs page), and
scripts/tests/test_topics.py fails while they're out of date or name a page that doesn't exist.
"""
from __future__ import annotations

import argparse
import glob
import json
import posixpath
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import generate_labs  # noqa: E402

DATA = ROOT / "data" / "topics.yml"
OUT = "docs/topics"
MEMBERS = ROOT / "assets" / "topic-members.json"
VIDEOS = ROOT / "docs" / "presentations" / "videos.json"
GITHUB = "https://github.com/WhalerMike/modernization-workbook"
BANNER = ("<!-- Generated by scripts/build_topics.py from data/topics.yml. "
          "Edit those, then run: python scripts/build_topics.py -->")

# Pages a topic links to that list every topic's material, so belong to none.
SHARED = {"docs/training/labs.md", "docs/training/index.md"}
# The hub's sections, in reading order.
SECTIONS = [
    ("understand", "Understand", "The design, in the books: why this topic matters and what the target is."),
    ("plan", "Plan", "The project plan and the decisions the program has made."),
    ("build", "Build", "The implementation guides, the developer workbook and its code."),
    ("learn", "Learn", "The learning path and its hands-on labs."),
    ("watch", "Watch", "Narrated videos. Each opens in the site's player, with chapters and captions."),
    ("download", "Download", "Word editions and code, rebuilt on every site deploy."),
    ("evidence", "Evidence", "The federal requirements each step supports, and the evidence it keeps."),
]
VIDEO_GROUPS = {"book": "Book and guide presentations", "developer": "Developer workbook chapter tours",
                "training": "Learning path modules", "research": "Research", "start": "Start series",
                "interview": "Interviews"}


def front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    try:
        return yaml.safe_load(text[3:end]) or {}
    except yaml.YAMLError:
        return {}


def first_sentence(text: str, limit: int = 240) -> str:
    text = re.sub(r"\s+", " ", str(text or "")).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    if len(s) > limit:
        s = s[: limit - 1].rsplit(" ", 1)[0] + "…"
    return s


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def rel(target: str, page: str) -> str:
    """Link from one site page to another (both repository paths)."""
    return posixpath.relpath(target, posixpath.dirname(page))


def page_entry(spec: dict, hub: str) -> tuple[str, str, str]:
    """(link, title, what it is) for a page entry."""
    path, _, anchor = spec["page"].partition("#")
    fm = front_matter(ROOT / path)
    title = fm.get("title") or Path(path).stem
    if path == "docs/about/decision-register.md" and re.fullmatch(r"wd-\d+", anchor):
        title = f"Decision {anchor.upper()}"  # one row per decision, named by its number
    note = spec.get("note") or first_sentence(fm.get("description") or fm.get("subtitle") or "")
    link = rel(path, hub) + (f"#{anchor}" if anchor else "")
    return link, str(title), note


def workbook(key: str) -> generate_labs.Workbook:
    for wb in generate_labs.WORKBOOKS:
        if wb.key == key:
            return wb
    raise SystemExit(f"data/topics.yml: no workbook {key!r} in scripts/generate_labs.py WORKBOOKS")


def entries(topic: dict) -> dict[str, list[dict]]:
    """Each section's page entries: the workbook's first, then the topic's own."""
    out = {key: [] for key, _, _ in SECTIONS}
    if topic.get("workbook"):
        wb = workbook(topic["workbook"])
        if wb.guide:
            out["build"].append({"page": wb.guide})
        out["build"].append({"page": f"{wb.docs}/index.md"})
        if wb.training:
            out["learn"].append({"page": f"{wb.training}/index.md"})
        out["learn"].append({"page": f"docs/training/labs.md#{wb.key}",
                             "note": f"Every lab in {wb.title}: what each needs, where it runs, and its commands."})
    # A learning path with no developer workbook behind it names its own page and Labs anchor.
    if topic.get("learning_path"):
        out["learn"].append(path_entry(topic))
    if topic.get("labs"):
        out["learn"].append({"page": f"docs/training/labs.md#{topic['labs']}",
                             "note": f"Every lab in the {topic['title']} learning path: what each needs, where it runs, and its commands."})
    for key, items in (topic.get("sections") or {}).items():
        if key not in out:
            raise SystemExit(f"data/topics.yml: {topic['id']}: unknown section {key!r}")
        out[key].extend(items)
    return out


def path_entry(topic: dict) -> dict:
    """The learning_path key as a page entry (it may be a path or a {page, note})."""
    lp = topic["learning_path"]
    return dict(lp) if isinstance(lp, dict) else {"page": lp}


def subject(topic: dict) -> str:
    """The topic's title as it reads mid-sentence."""
    return topic.get("subject") or topic["title"].lower()


def downloads(topic: dict) -> list[str]:
    names = list(topic.get("downloads") or [])
    if topic.get("workbook"):
        z = workbook(topic["workbook"]).zip
        if z not in names:
            names.insert(0, z)
    return names


def members(topic: dict) -> list[str]:
    """Every page that belongs to the topic (repository paths, sorted)."""
    pages = set()
    for items in entries(topic).values():
        for spec in items:
            pages.add(spec["page"].partition("#")[0])
    if topic.get("workbook"):
        wb = workbook(topic["workbook"])
        pages.update(glob.glob(f"{wb.docs}/*.md", root_dir=ROOT))
    folder = path_folder(topic)
    if folder:
        pages.update(glob.glob(f"{folder}/*.md", root_dir=ROOT))
    for pattern in topic.get("members") or []:
        pages.update(glob.glob(pattern, root_dir=ROOT))
    pages = {p.replace("\\", "/") for p in pages}
    # Pages whose names start with "_" (briefs, verification logs) and the Training and Labs pages
    # (every topic's paths and labs) aren't members.
    return sorted(p for p in pages if not Path(p).name.startswith("_") and p not in SHARED)


def videos(topic: dict, pages: list[str]) -> list[dict]:
    allv = json.loads(VIDEOS.read_text(encoding="utf-8"))
    extra = set(topic.get("videos") or [])
    known = {v["id"] for v in allv}
    missing = extra - known
    if missing:
        raise SystemExit(f"data/topics.yml: {topic['id']}: no such video {sorted(missing)}")
    member = set(pages)
    return [v for v in allv if v.get("source") in member or v["id"] in extra]


def hub_page(topic: dict) -> str:
    hub = f"{OUT}/{topic['id']}.md"
    pages = members(topic)
    secs = entries(topic)
    vids = videos(topic, pages)
    files = downloads(topic)
    lines = [
        "---",
        f'title: "Topic: {topic["title"]}"',
        f'subtitle: "Everything the workbook has on {subject(topic)}, in one place"',
        f'description: "{cell(first_sentence(topic["summary"], 400))}"',
        "doc-type: topic-hub",
        "hide-description: true",
        'fmw-eyebrow: "Topic"',
        "toc: true",
        "---",
        BANNER,
        "",
        topic["summary"].strip(),
        "",
        "Work down the page: understand the design, plan it, build it, learn it, watch it, download it, "
        "and keep the evidence. [All topics](index.md) lists the others.",
        "",
    ]
    for key, heading, intro in SECTIONS:
        if key == "watch":
            if not vids:
                continue
            lines += [f"## {heading} {{#{key}}}", "", intro, ""]
            for group, label in VIDEO_GROUPS.items():
                gv = [v for v in vids if v.get("group") == group]
                if not gv:
                    continue
                lines += ["| Video | Minutes |", "|---|---|"]
                watch = rel("docs/presentations/watch.md", hub).replace(".md", ".html")
                for v in sorted(gv, key=natural):
                    lines.append(f"| [{cell(v['title'])}]({watch}?v={v['id']}) | {v.get('minutes', '')} |")
                lines += ["", f": {label} {{.striped .hover}}", ""]
            continue
        if key == "download":
            if not files:
                continue
            lines += [f"## {heading} {{#{key}}}", "", intro, "", "| File | What it is |", "|---|---|"]
            for name in files:
                lines.append(f"| [{name}]({'../' * (hub.count('/'))}downloads/{name}) | {download_note(name)} |")
            lines += ["", ": Downloads {.striped .hover}", "",
                      "[Downloads](../downloads.md) lists every file the workbook publishes.", ""]
            continue
        items = secs[key]
        if not items:
            continue
        lines += [f"## {heading} {{#{key}}}", "", intro, "", "| Page | What it is |", "|---|---|"]
        for spec in items:
            link, title, note = page_entry(spec, hub)
            lines.append(f"| [{cell(title)}]({link}) | {cell(note)} |")
        lines += ["", f": {heading} {{.striped .hover}}", ""]
        if key == "build" and kits(topic):
            folders = [f"[`examples/{k}`]({GITHUB}/tree/main/examples/{k})" for k in kits(topic)]
            where = folders[0] if len(folders) == 1 else ", ".join(folders[:-1]) + " and " + folders[-1]
            lines += [f"The code is in {where} on GitHub, and in the code zip under [Download](#download).", ""]
    missing = [(COLUMNS[c], note) for c, note in (topic.get("gaps") or {}).items()]
    if missing:
        lines += ["## Not here {#gaps}", "",
                  f"What the workbook doesn't have on {subject(topic)}, and whether it should. "
                  "[All topics](index.md#gaps) shows the same for every topic.", "",
                  "| Missing | Why |", "|---|---|"]
        lines += [f"| {label} | {cell(note)} |" for label, note in missing]
        lines += ["", ": Not here {.striped .hover}", ""]
    return "\n".join(lines).rstrip() + "\n"


def kits(topic: dict) -> list[str]:
    kit = topic.get("kit") or []
    return [kit] if isinstance(kit, str) else list(kit)


# The Topics page's columns: what a topic can have, in reading order.
COLUMNS = {"book": "Book chapters", "plan": "Project plan", "guide": "Guide",
           "workbook": "Developer workbook", "path": "Learning path", "labs": "Labs",
           "videos": "Videos", "code": "Code"}
GAP_PREFIXES = ("Not needed, because ", "Needed: ")


def path_folder(topic: dict) -> str | None:
    """The folder that holds the topic's learning path modules, if the path has one."""
    if topic.get("workbook"):
        return workbook(topic["workbook"]).training
    lp = path_entry(topic)["page"].partition("#")[0] if topic.get("learning_path") else ""
    return lp.removesuffix("/index.md") if lp.endswith("/index.md") else None


def coverage(topic: dict) -> dict[str, str]:
    """Column -> what the topic has (a short count or name), or "" when it has none."""
    secs = entries(topic)
    pages = members(topic)
    wb = workbook(topic["workbook"]) if topic.get("workbook") else None
    numbered = lambda folder: len([p for p in pages if folder and p.startswith(folder + "/")  # noqa: E731
                                   and re.match(r"\d\d-", Path(p).name)])
    book = sum(1 for s in secs["understand"] if s["page"].startswith("docs/books/b"))
    plan = sum(1 for s in secs["plan"] if s["page"].startswith("docs/project-plans/")
               and "/developer-workbooks/" not in s["page"])
    guides = sum(1 for s in secs["build"] if s["page"].startswith("docs/books/guides/"))
    modules = numbered(path_folder(topic))
    if not modules and topic.get("learning_path"):
        # A path whose modules are pages of their own, listed in the topic's Learn section.
        modules = len([s for s in secs["learn"] if s["page"].startswith("docs/training/")
                       and s["page"].partition("#")[0] != path_entry(topic)["page"].partition("#")[0]
                       and "labs.md" not in s["page"]])
    has_path = bool((wb and wb.training) or topic.get("learning_path"))
    vids = len(videos(topic, pages))
    code = len([d for d in downloads(topic) if d.endswith(".zip")])
    return {
        "book": f"{book}" if book else "",
        "plan": f"{plan}" if plan else "",
        "guide": f"{guides}" if guides else "",
        "workbook": f"{numbered(wb.docs)} chapters" if wb else "",
        "path": (f"{modules} modules" if modules else "yes") if has_path else "",
        "labs": "yes" if (wb or topic.get("labs")) else "",
        "videos": f"{vids}" if vids else "",
        "code": f"{code} zip{'s' if code > 1 else ''}" if code else "",
    }


def natural(video: dict) -> list:
    """Sort key that puts Module 2 before Module 10."""
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", video["id"])]


def download_note(name: str) -> str:
    if name.endswith(".zip"):
        return "Code: the scripts, tests and fixtures, as committed"
    bundles = yaml.safe_load((ROOT / "scripts" / "bundles.yml").read_text(encoding="utf-8"))["bundles"]
    for b in bundles:
        if b["output"] == name or name in (b.get("aliases") or []):
            return f"Word edition: {cell(b.get('title') or name)}"
    return "Word edition"


def index_page(topics: list[dict], folded: list[dict]) -> str:
    lines = [
        "---",
        'title: "Topics"',
        'subtitle: "Everything the workbook has on a topic, in one place"',
        'description: "Topic hubs: for each topic, the book chapters, project plan, guides, developer '
        'workbook, learning path, labs, videos and downloads on one page, and what each topic lacks."',
        "doc-type: section-landing",
        'fmw-eyebrow: "Topics"',
        "---",
        BANNER,
        "",
        "The workbook's menus list things by kind: books, projects, training, labs, presentations, "
        "videos and downloads. A topic hub lists them by subject instead. Each hub starts with the "
        "design in the books and works down through the plan, the build, the training, the videos, "
        "the downloads and the evidence. Every page that belongs to a topic shows a link to its hub "
        "under its title.",
        "",
        "Each row shows what a topic has. A cell that says **gap** is something readers need and the "
        "workbook doesn't have yet; **not needed** is a deliberate absence. [What each topic lacks](#gaps) "
        "gives the reason for each.",
        "",
        "| Topic | " + " | ".join(COLUMNS.values()) + " |",
        "|---|" + "---|" * len(COLUMNS),
    ]
    gap_rows = []
    for t in topics:
        have = coverage(t)
        notes = t.get("gaps") or {}
        cells = []
        for col in COLUMNS:
            if have[col]:
                cells.append(have[col])
            else:
                note = notes.get(col, "")
                cells.append(f"[{'not needed' if note.startswith(GAP_PREFIXES[0]) else 'gap'}](#gaps)")
                gap_rows.append(f"| [{t['title']}]({t['id']}.md#gaps) | {COLUMNS[col]} | {cell(note)} |")
        lines.append(f"| [{t['title']}]({t['id']}.md) | " + " | ".join(cells) + " |")
    lines += ["", ": Topic hubs {.striped .hover}", ""]
    if gap_rows:
        lines += ["## What each topic lacks {#gaps}", "",
                  "A gap is filled only where readers need it. Where nothing is needed, the note says why.",
                  "", "| Topic | Missing | Why |", "|---|---|---|", *gap_rows, "",
                  ": What each topic lacks {.striped .hover}", ""]
    if folded:
        lines += ["## Covered inside another topic {#folded}", "",
                  "These subjects have pages of their own but no hub, because another hub already holds them.",
                  "", "| Subject | Hub | Why |", "|---|---|---|"]
        titles = {t["id"]: t["title"] for t in topics}
        for f in folded:
            lines.append(f"| {cell(f['title'])} | [{titles[f['into']]}]({f['into']}.md) | {cell(f['reason'])} |")
        lines += ["", ": Covered inside another topic {.striped .hover}", ""]
    return "\n".join(lines) + "\n"


def load() -> dict:
    return yaml.safe_load(DATA.read_text(encoding="utf-8"))


def outputs() -> dict[Path, str]:
    data = load()
    topics = data["topics"]
    files = {ROOT / OUT / "index.md": index_page(topics, data.get("folded") or [])}
    member_map: dict[str, list[dict]] = {}
    for t in topics:
        files[ROOT / OUT / f"{t['id']}.md"] = hub_page(t)
        for p in members(t):
            member_map.setdefault(p, []).append({"id": t["id"], "title": t["title"]})
    files[MEMBERS] = json.dumps(member_map, indent=1, ensure_ascii=False, sort_keys=True) + "\n"
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report out-of-date files; write nothing")
    args = ap.parse_args()
    stale = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode("utf-8"))
    for s in stale:
        print(("out of date: " if args.check else "wrote ") + s)
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
