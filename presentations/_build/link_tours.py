"""Write each developer-workbook tour's README and link the tours from the chapter pages, the workbook
landing pages and the Presentations page. Idempotent: run it again after a tour is re-recorded.

    python presentations/_build/link_tours.py "October 31, 2026"          # the recording date the pages show

The links on the chapter and landing pages sit between `<!-- tour:begin ... -->` and `<!-- tour:end -->`
markers, and the script replaces only what is between them. Lengths come from data/video-durations.json
(`scripts/generate_video_manifest.py --verify`), so upload the MP4s and refresh that first.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] if len(sys.argv) < 3 else Path(sys.argv[2])
DATE = sys.argv[1]  # e.g. "October 31, 2026"
# Each workbook's folder: Book 19 under Books, the others under Projects.
WB = {"adm": ("docs/books/b19-developer-workbook", "Building the Attribute-Driven Migration"),
      "pa": ("docs/project-plans/developer-workbooks/privileged-access", "Building Privileged Access"),
      "npi": ("docs/project-plans/developer-workbooks/non-person-identity", "Building Non-Person Identity")}
GH = "https://github.com/WhalerMike/modernization-workbook/blob/main"
REL = "https://github.com/WhalerMike/modernization-workbook/releases/download/videos-2026-10-23"
BEGIN = "<!-- tour:begin (generated by the tour build; not part of the reviewed page) -->"
END = "<!-- tour:end -->"
# A generated block always starts a line after a blank line and is followed by one blank line, so
# deleting the match (the same regex the review gate uses) gives back the page byte for byte.
MARKED = re.compile(r"^<!-- tour:begin[^\n]*-->\n.*?^<!-- tour:end -->\n\n", re.S | re.M)


def insert_marked(md: str, pos: int, content: str) -> str:
    assert md[pos - 2:pos] == "\n\n", "a tour block goes after a blank line"
    return md[:pos] + BEGIN + "\n\n" + content.strip("\n") + "\n\n" + END + "\n\n" + md[pos:]
durs = json.loads((ROOT / "data/video-durations.json").read_text(encoding="utf-8"))
sys.path.insert(0, str(ROOT / "scripts"))
import deck_assets  # noqa: E402


def deck(path: str, up: str) -> str:
    """A deck's link: its file on the current edition's Release (scripts/deck_assets.py), or, for a deck
    not published yet, its path here, which the deck link check reports until the next edition carries it."""
    return deck_assets.url(path) or up + path


def write(p: Path, text: str):
    p.write_bytes(text.encode("utf-8"))


tours = {k: [] for k in WB}
for folder in sorted((ROOT / "presentations").glob("dw-*")):
    m = re.match(r"dw-(adm|pa|npi)-(\d\d)-", folder.name)
    wb, nn = m.group(1), m.group(2)
    src = (folder / "build.js").read_text(encoding="utf-8")
    base = re.search(r'base:\s*"([^"]+)"', src).group(1)
    vid = f"{base}_Narrated"
    chdir = ROOT / WB[wb][0]
    page = next(chdir.glob(f"{nn}-*.md"))
    title = re.search(r'^title:\s*"Chapter \d\d — (.*)"\s*$', page.read_text(encoding="utf-8"), re.M).group(1)
    secs = durs.get(vid)
    mins = max(1, round(secs / 60)) if secs else None
    script = (folder / f"{base}_Narration_Script.md").read_text(encoding="utf-8")
    slides = len(re.findall(r"^## Slide \d+", script, re.M))
    words = sum(len(b.split()) for b in re.split(r"^## Slide .*$", script, flags=re.M)[1:])
    rel = folder.relative_to(ROOT).as_posix()
    pg = page.relative_to(ROOT).as_posix()
    write(folder / "README.md", f"""# {WB[wb][1]}, Chapter {nn} — {title}: narrated tour

**Deck name: {base}.** A narrated tour of [Chapter {nn} — {title}](../../{pg}) in the developer workbook *{WB[wb][1]}*. It is built with the shared kit in [`../_build/`](../_build/README.md): the slides and notes are data in `build.js`, laid out by [`../_build/devwb.js`](../_build/devwb.js). This folder sits outside `docs/`, so the site doesn't render it.

| File | Use |
|---|---|
| `{base}.pptx` | The deck: {slides} narrated slides (the title and {slides - 1} content slides in Why, What, Who and How order), then a backup section with the chapter's footnotes in full |
| `{base}_Narrated.pptx` | The self-running edition: narration audio and a caption track on every slide, backup section dropped |
| `{base}_Narrated.mp4` | The video{f", about {mins} minutes" if mins else ""}, on the [videos release]({REL}/{vid}.mp4) |
| `{base}_Narrated.vtt` | The video's caption track |
| `{base}_Narration_Script.md` | The spoken narration, slide by slide (about {words:,} words) |
| `build.js` | The slides, the spoken narration (`say`), the presenter detail (`detail`) and the chapter footnotes each slide cites (`cite`) |

Build (Git Bash): `source /c/tmp/deckenv.sh`, then `DATECODE="YYYY-MM-DD HH:MM ET" node {rel}/build.js`, with the Eastern time taken from PowerShell. Then `narrate.py`, `captions.py`, `build_narrated.ps1` and `export_mp4.ps1`, as in the kit's README; `qa_export.ps1` checks the layout through PowerPoint.

## Notes and sourcing

Each slide's speaker notes have three parts: the narration (the only part spoken), a Detail part with the chapter's full content for a presenter, and the chapter footnotes the slide relies on, in full, ending with the chapter sections it draws on. Every fact comes from the chapter; the deck adds none. The chapter's own labels carry over: design guidance, preview and beta stages, and points not confirmed. The example code is illustrative and tested against fixtures, not proven against a production tenant.

The title slide carries the Date Code of the build and the chapter's review status. The tour was recorded on {DATE} from the chapter as approved at the review gate; if the chapter changes, the tour is rebuilt and re-recorded.
""")
    # Chapter page: a tour callout right after the "In this chapter" callout.
    md = page.read_text(encoding="utf-8")
    md = MARKED.sub("", md)
    up = "../" * (len(page.relative_to(ROOT).parts) - 1)
    length = f"about {mins} minutes, " if mins else ""
    block = f"""::: {{.callout-tip appearance="simple"}}
## Narrated tour
{{{{< fmw-video {vid} >}}}}

[Deck]({deck(f'{rel}/{base}.pptx', up)}) · [Narrated deck]({deck(f'{rel}/{vid}.pptx', up)}) ({length}captions) · [Script]({GH}/{rel}/{base}_Narration_Script.md) · [Captions]({GH}/{rel}/{vid}.vtt). Recorded on {DATE} from the approved chapter.
:::
"""
    i = md.index("## In this chapter")
    j = md.index("\n:::\n", i) + len("\n:::\n")
    md = insert_marked(md, j + 1, block)
    write(page, md)
    tours[wb].append((nn, title, page.name, rel, base, vid, mins))

# Workbook indexes: a "Narrated chapter tours" section before "## How each chapter is built" is replaced or added after the chapter table.
for wb, rows in tours.items():
    if not rows:
        continue
    idx = ROOT / WB[wb][0] / "index.md"
    md = idx.read_text(encoding="utf-8")
    top = "../" * (len(idx.relative_to(ROOT).parts) - 1)  # the repository root
    docs = "../" * (len(idx.relative_to(ROOT).parts) - 2)  # docs/
    md = MARKED.sub("", md)
    lines = ["## Narrated chapter tours", "",
             f"Every chapter has a narrated tour: a deck in Why, What, Who and How order, a self-running edition with captions, and a video. "
             f"The tours were recorded on {DATE} from the approved chapters, and a tour is re-recorded when its chapter changes. "
             f"All of them are also on the [Watch page]({docs}presentations/watch.md).", "",
             "| # | Chapter | Watch | Length | Deck | Narrated deck |", "|---|---|---|---|---|---|"]
    for nn, title, fname, rel, base, vid, mins in rows:
        lines.append(f"| {nn} | [{title}]({fname}) | [▶ Watch]({docs}presentations/watch.html?v={vid}) · [MP4]({REL}/{vid}.mp4) | "
                     f"{f'{mins} min' if mins else '—'} | [{base}.pptx]({deck(f'{rel}/{base}.pptx', top)}) | "
                     f"[Narrated]({deck(f'{rel}/{vid}.pptx', top)}) |")
    block = "\n".join(lines)
    k = md.find("\n## ", md.index("## Chapters") + 5)
    md = insert_marked(md, k + 1, block)
    write(idx, md)
    print(f"{wb}: {len(rows)} tours linked")

# The Presentations page: one section with a table per workbook, before the HR-driven identity talk set.
pi = ROOT / "docs/presentations/index.md"
md = pi.read_text(encoding="utf-8")
md = re.sub(r"\n## Developer workbook chapter tours\n.*?(?=\n## )", "\n", md, flags=re.S)
out = ["", "## Developer workbook chapter tours", "",
       "Each chapter of [Book 19](../books/b19-developer-workbook/index.md) and of the two [developer workbooks](../project-plans/developer-workbooks/index.md) under Projects has a narrated tour of about ten minutes: "
       "why the chapter's code comes first, what Microsoft's own sample gives and leaves out, the code and its tests, who runs it, the two labs, the dangers and the checklist. "
       "The slides follow the Why, What, Who and How order of the book decks; each slide's notes carry the narration, the chapter's full detail and the footnotes it rests on.", ""]
for wb, rows in tours.items():
    if not rows:
        continue
    out += [f"### {WB[wb][1]}", "", "| Chapter | Deck | Narrated | Script and captions |", "|---|---|---|---|"]
    for nn, title, fname, rel, base, vid, mins in rows:
        page = f"../{WB[wb][0].removeprefix('docs/')}/{fname}"
        out.append(f"| [{nn} — {title}]({page}) | [Deck]({deck(f'{rel}/{base}.pptx', '../../')}) | [Narrated]({deck(f'{rel}/{vid}.pptx', '../../')}) "
                   f"({f'about {mins} min, ' if mins else ''}captions) · [▶ Watch](watch.html?v={vid}) · [MP4]({REL}/{vid}.mp4) | "
                   f"[Script]({GH}/{rel}/{base}_Narration_Script.md) · [Captions]({GH}/{rel}/{vid}.vtt) |")
    out += ["", f": {WB[wb][1]}, chapter tours {{.striped .hover}}", ""]
k = md.index("\n## HR-driven identity talk set")
md = md[:k] + "\n".join(out) + md[k:]
write(pi, md)
print("presentations index updated")
